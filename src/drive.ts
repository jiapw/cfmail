/** Hourly: abort multipart uploads that never completed
 *  每小时:中止一直没完成的分片上传 */
export async function driveCronHourly(env: Env): Promise<void> {
  const olds = await env.DB.prepare('SELECT * FROM drive_uploads WHERE created_at<?1 LIMIT 50')
    .bind(now() - UPLOAD_STALE_MS).all();
  for (const u of (olds.results || []) as any[]) {
    try {
      await env.RAW.resumeMultipartUpload(u.r2_key, u.upload_id).abort();
    } catch {}
    await env.DB.prepare('DELETE FROM drive_uploads WHERE id=?1').bind(u.id).run();
  }
}

/** Daily: purge trash older than 30 days, bounded per run (a huge subtree simply continues tomorrow)
 *  每天:清理回收站中超过 30 天的内容,每次运行有上限(特别大的子树明天接着删) */
export async function driveCronDaily(env: Env): Promise<void> {
  for (let i = 0; i < 3; i++) {
    const row = await env.DB.prepare('SELECT id FROM drive_nodes WHERE trashed=1 AND trashed_at<?1 LIMIT 1')
      .bind(now() - TRASH_KEEP_MS).first<any>();
    if (!row) break;
    await purgeSubtree(env, row.id, PURGE_BATCH);
  }
}
