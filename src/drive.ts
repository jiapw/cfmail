/** Do the two users have at least one domain in common (each holding some mailbox there)?
 *  两个用户是否至少同属一个域名(各自在该域名下有邮箱)? */
async function sharesDomainWith(env: Env, ownerId: string, userId: string): Promise<boolean> {
  const row = await env.DB.prepare(
    `SELECT 1 AS ok FROM grants g1 JOIN mailboxes m1 ON m1.id=g1.mailbox_id
     WHERE g1.user_id=?1 AND m1.domain_id IN (
       SELECT m2.domain_id FROM grants g2 JOIN mailboxes m2 ON m2.id=g2.mailbox_id WHERE g2.user_id=?2)
     LIMIT 1`
  ).bind(ownerId, userId).first();
  return !!row;
}

