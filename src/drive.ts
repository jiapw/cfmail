// Drive: Google-Drive-like per-user cloud storage. Bytes live in R2 under drive/<owner_id>/<file_id>;
// the folder tree is D1 metadata (drive_nodes), so rename/move never copies data (R2 has no rename).
// The switch is per domain; a user has Drive when any of their domains enables it, and the storage
// pool is one per user across domains. Quota: per-user override, else the largest default among the
// user's enabled domains, hard-capped at 10 GB. Sharing: one link per folder, viewer/editor, only for
// signed-in users sharing at least one domain with the owner.
//
// 网盘:Google Drive 风格的每用户云存储。字节存 R2 的 drive/<owner_id>/<file_id>;
// 目录树是 D1 元数据(drive_nodes),改名/移动不搬数据(R2 没有重命名)。
// 开关按域名;用户所属任一域名开启即可用,存储跨域名同一份。
// 配额:用户单独指定优先,否则取其已开启域名中最大的默认值,硬顶 10TB。
// 共享:每文件夹一条链接,查看者/编辑者两档,仅限与所有者至少同属一个域名的登录用户。
