export const driveApp = new Hono<Ctx>();

// In-isolate short-lived caches for the media streaming hot path. A video seek fires a fresh
// Range request, and each one was paying two to three SEQUENTIAL D1 round trips (quota gate,
// ancestor-chain access CTE, share membership) before R2 produced a single byte. Worker
// isolates live across requests, so a 60-second memory cache absorbs the burst that scrubbing
// the timeline generates. Scope: read-only file streaming; everything that mutates or displays
// live numbers keeps querying fresh. Revoking a share can lag a playing stream by up to 60s;
// deletes do not (R2 is already empty and answers 404).
// 流媒体热路径的 isolate 内存短时缓存。每次视频 seek 都是一个新的 Range 请求,
// 之前每个都要串行付 2-3 个 D1 往返(配额闸、祖先链权限 CTE、共享成员)之后 R2 才出第一个字节。
// Worker isolate 跨请求存活,60 秒的内存缓存正好吸收拖进度条产生的这阵请求风暴。
// 只作用于只读的文件流。所有写操作与实时数字仍然现查。撤销共享对正在播的流最多延迟 60 秒;
// 删除不受此影响(R2 已空,直接 404)。
const STREAM_TTL = 60 * 1000;
const quotaCache = new Map<string, { q: Quota; exp: number }>();
const accessCache = new Map<string, { node: NodeRow; exp: number }>();
const sweep = (m: Map<string, unknown>) => {
  if (m.size > 500) m.clear();
};

const isStreamRead = (c: any) => c.req.method === 'GET' && String(c.req.path || '').includes('/files/');

driveApp.use('*', requireAuth);
driveApp.use('*', async (c, next) => {
  const uid2 = c.get('user').id;
  let q: Quota | null = null;
  if (isStreamRead(c)) {
    const hit = quotaCache.get(uid2);
    if (hit && hit.exp > Date.now()) q = hit.q;
  }
  if (!q) {
    q = await driveQuota(c.env, uid2);
    sweep(quotaCache);
    quotaCache.set(uid2, { q, exp: Date.now() + STREAM_TTL });
  }
  if (!q.enabled) throw new HttpError(403, 'e_drive_disabled');
  c.set('dq', q);
  await next();
});

/** View access for streaming endpoints, memoised per (user, node) for 60 seconds
 *  流端点的读权限。按用户与节点记忆 60 秒 */
async function accessFileCached(c: any, nodeId: string): Promise<NodeRow> {
  const key = (c.get('user') as User).id + ':' + nodeId;
  const hit = accessCache.get(key);
  if (hit && hit.exp > Date.now()) return hit.node;
  const a = await accessNode(c, nodeId, 'view');
  sweep(accessCache);
  accessCache.set(key, { node: a.node, exp: Date.now() + STREAM_TTL });
  return a.node;
}

