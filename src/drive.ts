// Small files in one request: raw body, metadata in the query string
// 小文件一次请求:原始字节做 body,元数据放查询串
driveApp.post('/upload', async (c) => {
  // `node` targets an existing file directly: the caller needs edit rights on THAT FILE, not on
  // the folder holding it. That is what makes a single shared file updatable -- its recipient
  // was given the file, never the folder, so they have nowhere to "upload a file of the same
  // name" into. The name and location are fixed by the target; only the bytes change.
  // `node` 直接指向一个已有文件:调用者需要的是对"该文件"的编辑权,而不是对其所在目录的。
  // 正是这一点让"单独分享的文件"可被更新 —— 接收方拿到的是文件而非目录,
  // 他没有任何地方可以"上传一个同名文件"。名称与位置由目标锁定,变的只有内容。
  const overwriteId = String(c.req.query('node') || '');
  let target: WriteTarget;
  let name: string;
  let clash: NodeRow | null;
  if (overwriteId) {
    const a = await accessNode(c, overwriteId, 'edit');
    if (a.node.kind !== 'file') throw new HttpError(400, 'e_drive_not_file');
    if (a.chain.some((n) => n.trashed)) throw new HttpError(400, 'e_drive_trashed');
    target = { ownerId: a.node.owner_id, parentId: a.node.parent_id, versioned: !!a.node.versioned };
    name = a.node.name;
    clash = a.node;
  } else {
    target = await resolveWriteTarget(c, String(c.req.query('parent') || 'root'));
    name = cleanName(c.req.query('name'));
    // An occupied name means overwrite: the same node, carrying its star and its creation date
    // into new bytes. Whether the old bytes survive that is the file's own business -- one that
    // keeps history keeps them, an ordinary one lets the put replace them where they lie.
    // 名字被占用即覆盖:同一个节点,带着它的星标与创建时间换上新字节。
    // 旧字节能不能活下来,是这个文件自己的事 —— 保留历史的把它们留下,
    // 普通的就让 put 在原地替换掉。
    clash = await findClash(c.env, target.ownerId, target.parentId, name, 'file');
  }
  const mime = cleanMime(c.req.query('mime'));
  const hash = cleanHash(c.req.query('hash'));
  const len = parseInt(c.req.header('Content-Length') || '', 10);
  // An empty file is a thing somebody may want to make -- a document they are about to write into
  // -- and a body of zero bytes is how you would say so. Requiring a body said it could not be
  // said at all.
  // 空文件是有人可能想造出来的东西 —— 一份他正要往里写的文档 —— 而零字节的请求体正是这么说的方式。
  // 硬性要求有 body,等于说这件事根本说不出口。
  if (!Number.isFinite(len) || len < 0) throw new HttpError(400, 'e_drive_body_required');
  if (len > 0 && !c.req.raw.body) throw new HttpError(400, 'e_drive_body_required');
  if (len > SINGLE_MAX) throw new HttpError(413, 'e_drive_part_too_big');
  const oldSize = clash?.size || 0;
  const q0 = await driveQuota(c.env, target.ownerId);
  if (!q0.enabled) throw new HttpError(403, 'e_drive_disabled');
  if (q0.used - oldSize + len > q0.quota) throw new HttpError(413, 'e_drive_quota');
  // The conditional write is settled before a single byte reaches R2. A writer that named a stale
  // base is refused outright -- it asked to be told, and telling it afterwards would be telling it
  // about something it had already buried.
  // 条件写在任何一个字节到达 R2 之前就了结。指认了过期基准的写者会被直接拒绝 ——
  // 它请求过被告知,而事后再告知,说的就是一件它已经埋掉了的事。
  const versioned = clash ? !!clash.versioned : target.versioned;
  const head = clash ? await headVersion(c.env, clash) : null;
  const linked = clash ? gateBase(c, clash) : false;
  const id = clash ? clash.id : uid();
  const vid = uid();
  // A file that keeps history never writes over its own bytes: the new ones take a key of their
  // own and the node's pointer moves to them. That single move is the whole mechanism -- the old
  // version is not saved anywhere, it is simply never disturbed.
  // 保留历史的文件从不覆盖自己的字节:新的那份拿到属于它自己的键,节点的指针再移过去。
  // 这一次移动就是整套机制 —— 旧版本没有被"保存"到任何地方,它只是从未被惊动。
  const key = versioned && head
    ? `drive/${target.ownerId}/${id}.v${vid}`
    : (clash?.r2_key || `drive/${target.ownerId}/${id}`);
  // The digest travels as a condition, not as a note: R2 checks the body against it and fails the
  // write when they disagree. So the value that ends up in the row is one the bytes have already
  // answered for -- and the next upload can trust it enough to send nothing.
  // 摘要是作为条件而不是备注同行的:R2 拿请求体对着它验,不符就让这次写入失败。
  // 于是最终落进那一行的值,是字节已经为之作过答的 —— 下一次上传才敢凭它什么都不发。
  let obj: R2Object | null;
  try {
    obj = await c.env.RAW.put(key, len ? c.req.raw.body : new Uint8Array(0), {
      httpMetadata: { contentType: mime },
      ...(hash ? { sha256: hash } : {}),
    });
  } catch {
    throw new HttpError(400, 'e_drive_hash_mismatch');
  }
  const size = obj?.size ?? len;
  const t = now();
  const author = (c.get('user') as User).id;
  if (clash) {
    const stmts = [
      c.env.DB.prepare('UPDATE drive_nodes SET mime=?1, size=?2, has_thumb=0, updated_at=?3, r2_key=?4, ver_head=?5 WHERE id=?6')
        .bind(mime, size, t, key, versioned ? vid : clash.ver_head, id),
      c.env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes+?1,0) WHERE id=?2')
        .bind(size - oldSize, target.ownerId),
    ];
    if (versioned) {
      stmts.push(versionWrite(c.env, id, head, { id: vid, key, size, mime, origin: 'web', author, linked, hash, at: t }));
    } else {
      // The stale thumbnail dies with the old bytes / 旧缩略图随旧内容一起作废
      await c.env.RAW.delete(key + THUMB_SUFFIX).catch(() => {});
    }
    const ad = ancDelta(c.env, target.parentId, size - oldSize);
    if (ad) stmts.push(ad);
    await c.env.DB.batch(stmts);
    if (versioned) await pruneVersions(c.env, id);
    // The row this isolate is holding describes the file as it was a moment ago.
    // 这个 isolate 手里攥着的那一行,描述的是一瞬之前的这个文件。
    accessCache.delete(author + ':' + id);
    return c.json(nodeJson({
      ...clash, mime, size, has_thumb: 0, updated_at: t, r2_key: key,
      ver_head: versioned ? vid : clash.ver_head, tree_bytes: clash.tree_bytes,
    }));
  }
  // Re-check with the actual byte count; concurrent uploads may both have passed the pre-check
  // 用实际字节数复核一次;并发上传可能都通过了预检
  const q = await driveQuota(c.env, target.ownerId);
  if (q.used + size > q.quota) {
    await c.env.RAW.delete(key).catch(() => {});
    throw new HttpError(413, 'e_drive_quota');
  }
  {
    const stmts = [
      c.env.DB.prepare(
        `INSERT INTO drive_nodes (id, owner_id, parent_id, kind, name, mime, size, r2_key, versioned, ver_head, created_at, updated_at)
         VALUES (?1,?2,?3,'file',?4,?5,?6,?7,?8,?9,?10,?10)`
      ).bind(id, target.ownerId, target.parentId, name, mime, size, key, versioned ? 1 : 0, versioned ? vid : null, t),
      c.env.DB.prepare('UPDATE users SET drive_bytes=drive_bytes+?1 WHERE id=?2').bind(size, target.ownerId),
    ];
    // Born under a folder that keeps history, born with a first version. Nothing stood before it,
    // so the missing parent here means the beginning -- not a chain that somebody cut.
    // 出生在一个保留历史的目录下,就带着第一版出生。它前面没有站过任何东西,
    // 所以此处缺席的 parent 意味着开端 —— 而不是谁把链条剪断了。
    if (versioned) {
      stmts.push(versionWrite(c.env, id, null, { id: vid, key, size, mime, origin: 'web', author, linked: false, hash, at: t }));
    }
    const ad = ancDelta(c.env, target.parentId, size);
    if (ad) stmts.push(ad);
    await c.env.DB.batch(stmts);
  }
  return c.json(nodeJson({
    id, parent_id: target.parentId, kind: 'file', name, mime, size,
    versioned: versioned ? 1 : 0, ver_head: versioned ? vid : null, created_at: t, updated_at: t,
  }));
});

