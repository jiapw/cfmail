driveApp.post('/upload/:id/complete', async (c) => {
  const u = await getUpload(c);
  const body = await c.req.json<any>();
  const parts = (Array.isArray(body.parts) ? body.parts : [])
    .map((p: any) => ({ partNumber: parseInt(p.n, 10), etag: String(p.etag || '') }))
    .filter((p: any) => Number.isFinite(p.partNumber) && p.etag);
  if (!parts.length) throw new HttpError(400, 'e_bad_request');
  const mpu = c.env.RAW.resumeMultipartUpload(u.r2_key, u.upload_id);
  let obj: R2Object;
  try {
    obj = await mpu.complete(parts);
  } catch (e) {
    await mpu.abort().catch(() => {});
    await c.env.DB.prepare('DELETE FROM drive_uploads WHERE id=?1').bind(u.id).run();
    throw new HttpError(400, 'e_drive_upload_failed');
  }
  // The target folder may have been trashed or purged while the upload ran -- fall back to the root
  // 上传期间目标文件夹可能已进回收站或被删 —— 回落到根目录
  let parentId = u.parent_id;
  if (parentId) {
    const chain = await chainOf(c.env, parentId);
    if (!chain.length || chain.some((x) => x.trashed) || chain[0].owner_id !== u.owner_id || chain[0].kind !== 'folder') {
      parentId = null;
    }
  }
  // Occupied name = overwrite: the old node and its bytes go away, the new node inherits the
  // star and the creation date.
  // 名字被占用即覆盖。旧节点连同其字节移除,新节点继承星标与创建时间。
  const clash = await findClash(c.env, u.owner_id, parentId, u.name, 'file');
  const q = await driveQuota(c.env, u.owner_id);
  if (q.used - (clash?.size || 0) + obj.size > q.quota) {
    await c.env.RAW.delete(u.r2_key).catch(() => {});
    await c.env.DB.prepare('DELETE FROM drive_uploads WHERE id=?1').bind(u.id).run();
    throw new HttpError(413, 'e_drive_quota');
  }
  const t = now();
  if (clash) {
    await c.env.RAW.delete([clash.r2_key!, clash.r2_key + THUMB_SUFFIX]).catch(() => {});
  }
  const stmts = [
    ...(clash ? [c.env.DB.prepare('DELETE FROM drive_nodes WHERE id=?1').bind(clash.id)] : []),
    c.env.DB.prepare(
      `INSERT INTO drive_nodes (id, owner_id, parent_id, kind, name, mime, size, r2_key, starred, created_at, updated_at)
       VALUES (?1,?2,?3,'file',?4,?5,?6,?7,?8,?9,?10)`
    ).bind(u.id, u.owner_id, parentId, u.name, u.mime, obj.size, u.r2_key,
      clash ? clash.starred : 0, clash ? clash.created_at : t, t),
    c.env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes+?1,0) WHERE id=?2')
      .bind(obj.size - (clash?.size || 0), u.owner_id),
    c.env.DB.prepare('DELETE FROM drive_uploads WHERE id=?1').bind(u.id),
  ];
  // Overwrite replaces bytes under the same parent, so one net delta covers both
  // 覆盖发生在同一父目录下,一条净增量同时涵盖旧去新来
  const ad = ancDelta(c.env, parentId, obj.size - (clash?.size || 0));
  if (ad) stmts.push(ad);
  await c.env.DB.batch(stmts);
  return c.json(nodeJson({
    id: u.id, parent_id: parentId, kind: 'file', name: u.name, mime: u.mime, size: obj.size, created_at: t, updated_at: t,
  }));
});

