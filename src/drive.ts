function parseRange(h: string | undefined): any {
  if (!h) return null;
  const m = /^bytes=(\d*)-(\d*)$/.exec(h.trim());
  if (!m || (!m[1] && !m[2])) return null;
  if (!m[1]) return { suffix: parseInt(m[2], 10) };
  const offset = parseInt(m[1], 10);
  if (!m[2]) return { offset };
  const end = parseInt(m[2], 10);
  if (end < offset) return null;
  return { offset, length: end - offset + 1 };
}

driveApp.get('/files/:id/dl', async (c) => {
  const node = await accessFileCached(c, c.req.param('id'));
  if (node.kind !== 'file' || !node.r2_key) throw new HttpError(400, 'e_drive_not_file');
  const range = parseRange(c.req.header('Range'));
  const obj: any = await c.env.RAW.get(node.r2_key, range ? { range } : undefined);
  if (!obj) throw new HttpError(404, 'e_drive_not_found');
  const mime = (node.mime || '').toLowerCase();
  const inline = c.req.query('inline') === '1' && INLINE_MIMES.has(mime);
  const h = new Headers();
  h.set('X-Content-Type-Options', 'nosniff');
  h.set('Accept-Ranges', 'bytes');
  h.set('Cache-Control', 'private, max-age=3600');
  h.set('ETag', `"${node.id}-${node.updated_at}"`);
  h.set('Content-Type', inline ? (mime === 'text/plain' ? 'text/plain; charset=utf-8' : mime) : mime || 'application/octet-stream');
  h.set('Content-Disposition', `${inline ? 'inline' : 'attachment'}; filename*=UTF-8''${encodeURIComponent(node.name)}`);
  if (range) {
    const r: any = obj.range || {};
    let off = 0;
    let len = obj.size;
    if (typeof r.offset === 'number') {
      off = r.offset;
      len = typeof r.length === 'number' ? r.length : obj.size - off;
    } else if (typeof r.suffix === 'number') {
      off = Math.max(0, obj.size - r.suffix);
      len = obj.size - off;
    }
    h.set('Content-Range', `bytes ${off}-${off + len - 1}/${obj.size}`);
    h.set('Content-Length', String(len));
    return new Response(obj.body, { status: 206, headers: h });
  }
  h.set('Content-Length', String(obj.size));
  return new Response(obj.body, { headers: h });
});

