// The uploading client renders the thumbnail (image crop, video frame pick, PDF/text screenshot)
// and posts it here as WebP. The server only checks the magic bytes and the size cap -- and always
// serves the result as image/webp + nosniff, so a bogus "thumbnail" can never become same-origin
// script (the /cid lesson).
// 缩略图由上传端渲染(图片裁切、视频选帧、PDF/文本截图),以 WebP POST 到这里。服务端只验魔数
// 和大小上限 —— 且永远按 image/webp + nosniff 回出去,假"缩略图"成不了同源脚本(/cid 的教训)。
driveApp.post('/files/:id/thumb', async (c) => {
  const a = await accessNode(c, c.req.param('id'), 'edit');
  if (a.node.kind !== 'file' || !a.node.r2_key) throw new HttpError(400, 'e_drive_not_file');
  const len = parseInt(c.req.header('Content-Length') || '', 10);
  if (!Number.isFinite(len) || len <= 0) throw new HttpError(400, 'e_drive_body_required');
  if (len > THUMB_MAX_BYTES) throw new HttpError(413, 'e_drive_part_too_big');
  const buf = await c.req.arrayBuffer();
  if (buf.byteLength > THUMB_MAX_BYTES) throw new HttpError(413, 'e_drive_part_too_big');
  const b = new Uint8Array(buf);
  const tag = (o: number) => String.fromCharCode(b[o], b[o + 1], b[o + 2], b[o + 3]);
  if (b.length < 12 || tag(0) !== 'RIFF' || tag(8) !== 'WEBP') throw new HttpError(400, 'e_bad_request');
  await c.env.RAW.put(a.node.r2_key + THUMB_SUFFIX, buf, { httpMetadata: { contentType: 'image/webp' } });
  await c.env.DB.prepare('UPDATE drive_nodes SET has_thumb=1 WHERE id=?1').bind(a.node.id).run();
  // The uploader's own stream cache may still say has_thumb=0 / 上传者自己的流缓存可能还记着没有缩略图
  accessCache.delete(c.get('user').id + ':' + a.node.id);
  return c.json({ ok: true });
});

