// ---------- Agent access links (/agt/<token>) ----------
// ---------- 面向 AI 的访问链接(/agt/<token>) ----------
//
// A share for a reader that is a program. Everything an agent needs arrives in the first
// response: a few lines of orders naming the tool and the verbs, then the contents of the link.
// There is no manifest to install, no server to configure, no second document to fetch --
// the URL is the instructions, and every deeper URL is reached by appending a name to the one
// it just read.
//
// The token sits in the path, so a single string carries both "who may" and "what". There is
// no session, no header to set, nothing to remember between requests. That is the whole point
// and also the whole risk, and it is a deliberate trade the owner makes when creating the link:
// whoever holds it can do what the link says, until the owner revokes it.
//
// Written to be read by a language model, so it is written to be short. Read-only links do not
// mention writing at all -- describing a verb the link will refuse is worse than useless, it is
// tokens spent to produce a wrong attempt.
//
// 一份写给"读者是程序"的共享。代理所需的一切都在第一次响应里到齐:寥寥数行说明有哪些动词,
// 接着就是这条链接的内容。没有清单要安装,没有服务要配置,没有第二份文档要取 ——
// URL 本身就是说明书,而更深处的每个 URL,都由刚读到的那个 URL 追加一个名字得到。
//
// token 在路径里,于是一个字符串同时携带"谁可以"和"什么"。没有会话,没有要设的头,
// 请求之间不必记住任何东西。这既是它的全部意义,也是它的全部风险 ——
// 这是所有者在创建链接时有意做出的交换:持有者能做链接所说的事,直到所有者撤销它。
//
// 它是写给语言模型读的,所以写得短。只读链接压根不提写 ——
// 描述一个链接会拒绝的动词,比无用更糟:那是花掉 token 去换一次错误的尝试。

export const driveAgentApp = new Hono<Ctx>();

driveAgentApp.use('*', async (c, next) => {
  await next();
  // Revocation has to bite at once; a cached 200 would outlive the link.
  // 撤销必须立刻生效;缓存下来的 200 会让链接活过它的死期。
  c.header('Cache-Control', 'no-store');
  c.header('X-Robots-Tag', 'noindex, nofollow');
});

/** Plain text in, plain text out. These answers are read by a model, not rendered, so an error
 *  is a short sentence rather than a code the caller would have to look up.
 *  纯文本进,纯文本出。这些回答是给模型读的、不做渲染,所以错误是一句短话,
 *  而不是一个还要去查表的错误码。 */
const txt = (body: string, status = 200) =>
  new Response(body, {
    status,
    headers: { 'Content-Type': 'text/plain; charset=utf-8', 'X-Content-Type-Options': 'nosniff' },
  });

/** Sizes an agent reads to decide whether to fetch something, not to do arithmetic on.
 *  给代理判断"要不要取"用的大小,不是拿来做算术的。 */
function shortSize(n: number): string {
  if (n < 1024) return `${n}`;
  const units = ['K', 'M', 'G', 'T'];
  let v = n / 1024;
  let i = 0;
  while (v >= 1024 && i < units.length - 1) { v /= 1024; i++; }
  return `${v >= 10 ? Math.round(v) : v.toFixed(1)}${units[i]}`;
}

/** Enough of a type map that text an agent writes comes back as text. Anything unrecognised is
 *  octet-stream, which is the honest answer and still downloads and previews as a file.
 *  够用的类型表,好让代理写进去的文本能按文本回来。认不出的一律 octet-stream ——
 *  这是诚实的答案,而且照样能下载、能当文件预览。 */
const EXT_MIME: Record<string, string> = {
  txt: 'text/plain', md: 'text/markdown', csv: 'text/csv', tsv: 'text/tab-separated-values',
  json: 'application/json', jsonl: 'application/json', ndjson: 'application/json',
  yaml: 'text/yaml', yml: 'text/yaml', toml: 'text/plain', ini: 'text/plain', log: 'text/plain',
  html: 'text/html', css: 'text/css', js: 'text/javascript', mjs: 'text/javascript',
  ts: 'text/plain', tsx: 'text/plain', jsx: 'text/plain', py: 'text/x-python', sh: 'text/x-sh',
  sql: 'text/plain', xml: 'application/xml', svg: 'image/svg+xml', pdf: 'application/pdf',
  png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', gif: 'image/gif', webp: 'image/webp',
  zip: 'application/zip', mp4: 'video/mp4', mp3: 'audio/mpeg',
};

function mimeOf(name: string, declared?: string | null): string {
  const d = String(declared || '').toLowerCase().split(';')[0].trim();
  if (d && d !== 'application/octet-stream' && /^[a-z0-9.+-]+\/[a-z0-9.+-]+$/.test(d)) return d.slice(0, 120);
  const ext = (/\.([A-Za-z0-9]{1,12})$/.exec(name) || ['', ''])[1].toLowerCase();
  return EXT_MIME[ext] || 'application/octet-stream';
}

async function agentShare(env: Env, token: string): Promise<any | null> {
  if (!token) return null;
  const s = await env.DB.prepare("SELECT * FROM drive_shares WHERE token=?1 AND audience='agent'")
    .bind(token).first();
  return shareLiveness(s) ? null : s;
}

/** The names the selected items answer to at the top level. Two items may well arrive carrying
 *  the same name from different folders, and a path has to mean one thing, so a repeat gets a
 *  `~2` suffix. The order is shareItems' order, so the same share always yields the same names.
 *  被选中的条目在顶层各自应答的名字。两个条目完全可能从不同目录带来同一个名字,
 *  而一条路径只能有一个含义,所以重复者补一个 `~2` 后缀。
 *  顺序即 shareItems 的顺序,于是同一条共享永远得到同一组名字。 */
async function agentRoots(env: Env, shareId: string): Promise<Map<string, NodeRow>> {
  const out = new Map<string, NodeRow>();
  for (const n of await shareItems(env, shareId)) {
    let seg = n.name;
    for (let k = 2; out.has(seg); k++) seg = `${n.name}~${k}`;
    out.set(seg, n);
  }
  return out;
}

/** Walk a path of names down from the selection. Intermediate segments must be folders; the last
 *  one is a file if a file by that name exists, otherwise a folder -- so an agent that forgets
 *  the trailing slash on a folder still gets its listing instead of an error.
 *  从选中项出发,按名字逐级往下走。中间的段必须是目录;最后一段若有同名文件就是文件,
 *  否则是目录 —— 于是代理忘了给目录加尾斜杠,拿到的仍是列表而不是报错。 */
async function agentWalk(env: Env, roots: Map<string, NodeRow>, segs: string[]): Promise<NodeRow | null> {
  if (!segs.length) return null;
  let node = roots.get(segs[0]) || null;
  if (!node) return null;
  for (let i = 1; i < segs.length; i++) {
    if (node.kind !== 'folder') return null;
    const row: any = await env.DB.prepare(
      `SELECT * FROM drive_nodes WHERE parent_id=?1 AND name=?2 AND trashed=0
        ORDER BY kind='file' DESC LIMIT 1`
    ).bind(node.id, segs[i]).first();
    if (!row) return null;
    node = row as NodeRow;
  }
  return node;
}

async function agentList(env: Env, folderId: string): Promise<string> {
  const rows = await env.DB.prepare(
    `SELECT name, kind, size FROM drive_nodes WHERE parent_id=?1 AND trashed=0
      ORDER BY kind DESC, name LIMIT ${LIST_LIMIT}`
  ).bind(folderId).all();
  return (rows.results || []).map((n: any) =>
    n.kind === 'folder' ? `${n.name}/` : `${n.name}\t${shortSize(n.size || 0)}`).join('\n');
}

const rootList = (roots: Map<string, NodeRow>): string =>
  [...roots].map(([seg, n]) => (n.kind === 'folder' ? `${seg}/` : `${seg}\t${shortSize(n.size || 0)}`)).join('\n');

/** Orders, not a datasheet. The reader is a model about to act, so the first sentence tells it
 *  what to do and which tool to do it with; a title and a spec would leave the choice of tool
 *  open, and the wrong choice is a specific, likely one -- a URL invites a browser, and a
 *  browsing tool here loads bytes into a viewport, cannot issue PUT or DELETE, and burns a
 *  screenshot on what is already plain text.
 *
 *  Every line is paid for on every visit, so a line earns its place by preventing a wrong
 *  request. The verbs a read-only link refuses go unmentioned: naming them only buys a 403.
 *
 *  是命令,不是数据表。读者是一个即将动手的模型,所以第一句就说清要做什么、用什么工具做;
 *  写成标题加规格,等于把工具的选择敞开着,而选错的方式既具体又大概率发生 ——
 *  一个 URL 会招来浏览器,而浏览工具在这里只会把字节装进视口,发不出 PUT 和 DELETE,
 *  还要为本来就是纯文本的东西烧掉一张截图。
 *
 *  这里每一行在每次访问时都要付账,所以一行要靠"能防住一次错误请求"来挣得位置。
 *  只读链接会拒绝的动词一概不提:提了只能换来一个 403。 */
function agentInstructions(base: string, share: any, roots: Map<string, NodeRow>): string {
  const rw = share.role === 'editor';
  if (share.agent_mode === 'dav') return agentMountInstructions(base, rw, roots);
  const lines = [
    `${rw ? 'Read and write' : 'Read'} these files over HTTP -- curl, or a request from code. Not a`,
    'browser or a browsing tool: these URLs return bytes, not pages.',
    '',
    `B=${base}`,
    '',
    'GET B/P/ list folder: a line per entry, name/ = folder, name<tab>size = file',
    'GET B/P read file (Range ok), ETag = the version you got',
    ...(rw ? [
      'PUT B/P write file, body = the whole new content; ETag = the version you made',
      'PUT B/P/ new folder',
      'DELETE B/P delete',
      'POST B/P?to=NAME rename',
    ] : []),
    '',
    'P is a path of names -- append a listed one to the URL you fetched to go deeper.',
    // Told in the imperative, and told what to DO with a 412 rather than what it means. A model
    // that reads "the precondition failed" writes an apology; one that reads "GET it again, redo
    // your edit, retry" closes the loop by itself -- and closing that loop is the one thing here
    // no person is around to do.
    // 用祈使句说,而且说的是拿 412 该"做什么",不是它"意味着什么"。
    // 读到"前置条件失败"的模型会写一句道歉;读到"重新 GET、重做你的修改、再试一次"的模型
    // 会自己把这个环闭上 —— 而闭上这个环,恰恰是这里没有任何人在场能代劳的事。
    ...(rw ? [
      'Create only inside a folder listed below.',
      '',
      'PUT with If-Match: ETAG to write only if the file is still the one you read.',
      '412 = it changed since. GET it again, redo your edit on the new bytes, PUT with the new ETag.',
      'Without If-Match the write still lands -- on top of a change you never read.',
    ] : []),
    '',
    'B:',
    rootList(roots),
  ];
  return lines.join('\n') + '\n';
}

/** The other introduction: put it on the filesystem and then forget it is remote. Written for a
 *  reader that will run one command and then use its ordinary tools, so what it needs is the
 *  command and the fact that there is no password -- not a protocol tour.
 *
 *  The three clients are named because "use a WebDAV client" is the kind of instruction that
 *  sends a model looking for one; naming rclone and the two file managers means it can act on
 *  the first read.
 *
 *  另一种自我介绍:把它放到文件系统上,然后忘掉它在远端。写给一个"跑一条命令、之后用自己
 *  惯常工具"的读者,所以它需要的是那条命令,以及"没有密码"这件事 —— 而不是一趟协议导览。
 *
 *  三种客户端点名写出来,是因为"用一个 WebDAV 客户端"这种说法,会让模型跑去找一个;
 *  点名 rclone 和两个文件管理器,它读第一遍就能动手。 */
function agentMountInstructions(base: string, rw: boolean, roots: Map<string, NodeRow>): string {
  return [
    'Mount this as a local folder, then use your ordinary file tools on it.',
    'Use rclone or the OS file manager -- not a browser or a browsing tool.',
    '',
    `U=${base}`,
    '',
    'There is no username or password: the URL is the credential.',
    'rclone mount --webdav-url U --webdav-vendor other :webdav: DIR',
    'macOS: Finder, Go > Connect to Server, U',
    'Windows: File Explorer, Map network drive, U',
    '',
    ...(rw
      ? ['Create, rename and delete as normal files. Locks are honoured, and lapse ten minutes',
        'after a client stops refreshing them.']
      : ['The mount is read-only.']),
    '',
    'U contains:',
    rootList(roots),
  ].join('\n') + '\n';
}

/** One handler for every method: the path is parsed the same way each time, and a trailing
 *  slash is meaningful, so it is read off the raw URL rather than from a router that may
 *  normalise it away.
 *  一个 handler 应付所有方法:路径每次都用同一套解析,而尾斜杠是有含义的,
 *  所以直接从原始 URL 上读,而不是交给可能把它规整掉的路由。 */
driveAgentApp.all('/*', async (c) => {
  const parts = new URL(c.req.url).pathname.split('/').slice(2);
  const token = parts.shift() || '';
  const wantDir = parts.length > 0 && parts[parts.length - 1] === '';
  if (wantDir) parts.pop();
  if (parts.some((s) => s === '')) return txt('bad path', 400);
  let segs: string[];
  try {
    segs = parts.map((s) => decodeURIComponent(s));
  } catch {
    return txt('bad path', 400);
  }
  // The URL parser collapses these before we ever see them, and a collapsed path can only land
  // on another token, never outside /agt. This is the backstop for the day that stops being true.
  // URL 解析器在我们看到之前就把它们折叠掉了,而折叠后的路径只可能落到另一个 token 上,
  // 出不了 /agt。这行是留给"哪天这条不再成立"的后手。
  if (segs.some((s) => s === '.' || s === '..')) return txt('bad path', 400);

  const share = await agentShare(c.env, token);
  // Wrong, revoked and expired answer alike: a link that no longer works is not worth
  // explaining to a program, and the distinction would only describe someone else's link.
  // 错误的、已撤销的、已过期的一律同一个回答:失效的链接不值得向程序解释,
  // 而分辨它们只会泄露别人那条链接的状态。
  if (!share) return txt('no such link', 404);
  const method = c.req.method;
  const write = method === 'PUT' || method === 'DELETE' || method === 'POST';
  if (write && share.role !== 'editor') return txt('read-only link', 403);

  const roots = await agentRoots(c.env, share.id);
  const node = segs.length ? await agentWalk(c.env, roots, segs) : null;

  // The other face of the same link. Which one you are talking to is decided by the method, so
  // a client that mounts and a program that curls can hold the very same URL.
  // 同一条链接的另一副面孔。你在跟哪一副说话由方法决定,
  // 于是"挂载的客户端"和"curl 的程序"可以攥着一模一样的 URL。
  if (DAV_METHODS.has(method)) return davHandle(c, share, roots, node, segs, token);
  // A lock taken by a mounted volume holds against the plain verbs too. It would be no lock at
  // all if the other face could write straight through it, and an agent that gets 423 is being
  // told something true: a person has this file open.
  // 挂载的卷所持有的锁,对朴素动词同样有效。如果另一副面孔能径直写穿过去,那就根本不算锁;
  // 而拿到 423 的代理,被告知的是一件真事:有人正开着这个文件。
  if (write) {
    const blocked = await davBlocked(c, share, segs);
    if (blocked) return blocked;
  }

  if (method === 'GET' || method === 'HEAD') {
    if (!segs.length) {
      // Taken from the request, not from a configured value: this instance answers on five
      // domains and the agent must be sent back to the one it actually reached. (wrangler dev
      // rewrites both the URL and the Host header to the first configured route, so the base
      // printed by a local server names a production host. Nothing to fix -- there is no
      // localhost answer to be had from a request that no longer says localhost.)
      // 取自请求本身,而不是某个配置值:本实例应答五个域名,必须把代理指回它真正到达的那个。
      // (wrangler dev 会把 URL 和 Host 头一起改写成配置里的第一条路由,
      // 因此本地服务器印出的 base 写的是生产域名。这没什么可修的 ——
      // 一个已经不再自称 localhost 的请求,给不出 localhost 这个答案。)
      const base = new URL(c.req.url).origin + '/agt/' + token;
      return txt(agentInstructions(base, share, roots));
    }
    if (!node) return txt('no such path', 404);
    if (node.kind === 'folder') return txt(await agentList(c.env, node.id) + '\n');
    const r = await serveFile(c, node);
    // Say utf-8 out loud on text. A browser has a document to take the encoding from; a program
    // reading `text/plain` with no charset is entitled to fall back to latin-1, and then every
    // non-ASCII file in the drive comes back as mojibake.
    // 文本要把 utf-8 说出口。浏览器有文档可据以推断编码;而一个读到不带 charset 的 text/plain
    // 的程序,有权退回 latin-1 —— 于是网盘里每个非 ASCII 文件都变成乱码。
    const ct = r.headers.get('Content-Type') || '';
    if (!ct.includes('charset') && /^(text\/|application\/(json|xml))/.test(ct)) {
      r.headers.set('Content-Type', `${ct}; charset=utf-8`);
    }
    return r;
  }

  if (method === 'DELETE') {
    if (!node) return txt('no such path', 404);
    // Into the owner's trash, not out of existence: the link is a convenience, and a convenience
    // should not be the one door in this system that destroys something irreversibly.
    // 进所有者的回收站,而不是从世上消失:这条链接图的是方便,
    // 而方便不该成为本系统里唯一一扇能不可逆地毁掉东西的门。
    const stmts = [
      c.env.DB.prepare('UPDATE drive_nodes SET trashed=1, trashed_at=?1, updated_at=?1 WHERE id=?2')
        .bind(now(), node.id),
    ];
    const ad = ancDelta(c.env, node.parent_id, -nodeBytes(node));
    if (ad) stmts.push(ad);
    await c.env.DB.batch(stmts);
    return txt('ok');
  }

  if (method === 'POST') {
    if (!node) return txt('no such path', 404);
    let name: string;
    try {
      name = cleanName(c.req.query('to'));
    } catch {
      return txt('bad name', 400);
    }
    if (await findClash(c.env, node.owner_id, node.parent_id, name, node.kind)) return txt('name taken', 409);
    await c.env.DB.prepare('UPDATE drive_nodes SET name=?1, updated_at=?2 WHERE id=?3')
      .bind(name, now(), node.id).run();
    return txt('ok');
  }

  // PUT: the last segment is the name being written, everything before it says where.
  // PUT:最后一段是要写的名字,它前面的部分说明写在哪儿。
  if (method !== 'PUT') return txt('unsupported method', 405);
  const fixed = 'the top level is fixed; write inside a listed folder';
  if (!segs.length) return txt(fixed, 400);

  // A top-level name is not a place to create things -- the root is the selection, not a folder.
  // But writing to something already listed there replaces it, and that is the whole point of
  // sharing one file with an agent: it has no folder here to put a new file in, only that file.
  // 顶层的名字不是可供创建的地方 —— 根是"所选内容",不是目录。
  // 但写到已经列在那里的东西上,是替换它;而这正是"把一个文件分享给 AI"的全部意义:
  // 它在这里没有目录可放新文件,只有那一个文件。
  let parent: NodeRow | null = null;
  let name: string;
  let clash: NodeRow | null = null;
  if (segs.length === 1) {
    if (!node) return txt(fixed, 400);
    if (wantDir) return node.kind === 'folder' ? txt('ok') : txt('not a folder', 400);
    if (node.kind !== 'file') return txt('not a file', 400);
    clash = node;
    name = node.name;
  } else {
    parent = await agentWalk(c.env, roots, segs.slice(0, -1));
    if (!parent) return txt('no such folder', 404);
    if (parent.kind !== 'folder') return txt('not a folder', 400);
    try {
      name = cleanName(segs[segs.length - 1]);
    } catch {
      return txt('bad name', 400);
    }
  }
  const ownerId = clash ? clash.owner_id : parent!.owner_id;
  const parentId = clash ? clash.parent_id : parent!.id;
  const q0 = await driveQuota(c.env, ownerId);
  if (!q0.enabled) return txt('drive disabled', 403);

  if (wantDir) {
    const existing = await findClash(c.env, ownerId, parentId, name, 'folder');
    if (existing) return txt('ok');
    const chain = await chainOf(c.env, parent!.id);
    if (chain.length >= DEPTH_MAX - 1) return txt('too deep', 400);
    const t = now();
    await c.env.DB.prepare(
      `INSERT INTO drive_nodes (id, owner_id, parent_id, kind, name, created_at, updated_at)
       VALUES (?1,?2,?3,'folder',?4,?5,?5)`
    ).bind(uid(), ownerId, parentId, name, t).run();
    return txt('ok');
  }

  const len = parseInt(c.req.header('Content-Length') || '', 10);
  if (!c.req.raw.body || !Number.isFinite(len) || len < 0) return txt('body required', 400);
  if (len > SINGLE_MAX) return txt(`too big, max ${shortSize(SINGLE_MAX)}`, 413);
  if (!clash) clash = await findClash(c.env, ownerId, parentId, name, 'file');
  const oldSize = clash?.size || 0;
  if (q0.used - oldSize + len > q0.quota) return txt('out of space', 413);
  const mime = mimeOf(name, c.req.header('Content-Type'));
  // This door may be written to conditionally, and most of what mounts it never will. Naming a
  // base that is no longer current is refused rather than merged -- there is nobody here to ask,
  // and guessing on someone's behalf is how the wrong half of a file goes missing. Naming none is
  // the ordinary case, and it is written down as the cut it makes.
  // 这扇门可以做条件写,而挂载它的东西大多永远不会。指认了一个已不是最新的基准,是被拒绝而不是被
  // 合并 —— 这里没有人可问,而替别人猜,正是一个文件丢掉错误的那一半的方式。
  // 什么都不指认才是常态,它会被如实记下为它所造成的那次切断。
  const base = clash ? namedBase(c) : null;
  if (base && base !== etagOf(clash!)) return txt('stale base, re-read the file first', 412);
  const versioned = clash
    ? !!clash.versioned
    : (parent ? (await chainOf(c.env, parent.id)).some((x) => x.ver_policy) : false);
  const head = clash ? await headVersion(c.env, clash) : null;
  const id = clash ? clash.id : uid();
  const vid = uid();
  const key = versioned && head ? `drive/${ownerId}/${id}.v${vid}` : (clash?.r2_key || `drive/${ownerId}/${id}`);
  const obj: any = await c.env.RAW.put(key, c.req.raw.body, { httpMetadata: { contentType: mime } });
  const size = obj?.size ?? len;
  const t = now();
  const stmts = clash
    ? [
      c.env.DB.prepare('UPDATE drive_nodes SET mime=?1, size=?2, has_thumb=0, updated_at=?3, r2_key=?4, ver_head=?5 WHERE id=?6')
        .bind(mime, size, t, key, versioned ? vid : clash.ver_head, id),
      c.env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes+?1,0) WHERE id=?2')
        .bind(size - oldSize, ownerId),
    ]
    : [
      c.env.DB.prepare(
        `INSERT INTO drive_nodes (id, owner_id, parent_id, kind, name, mime, size, r2_key, versioned, ver_head, created_at, updated_at)
         VALUES (?1,?2,?3,'file',?4,?5,?6,?7,?8,?9,?10,?10)`
      ).bind(id, ownerId, parentId, name, mime, size, key, versioned ? 1 : 0, versioned ? vid : null, t),
      c.env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes+?1,0) WHERE id=?2').bind(size, ownerId),
    ];
  if (versioned) {
    // No author: a token is not a person. Which door it came through is all this row can honestly
    // say about who wrote it.
    // 没有作者:令牌不是人。它从哪扇门进来,是这一行能对"是谁写的"诚实说出的全部。
    stmts.push(versionWrite(c.env, id, head, {
      id: vid, key, size, mime, origin: 'link', author: null, linked: !!base, at: t,
    }));
  } else if (clash) {
    // The stale thumbnail dies with the bytes it described / 旧缩略图随它所描述的字节一起作废
    await c.env.RAW.delete(key + THUMB_SUFFIX).catch(() => {});
  }
  const ad = ancDelta(c.env, parentId, size - oldSize);
  if (ad) stmts.push(ad);
  await c.env.DB.batch(stmts);
  if (versioned) await pruneVersions(c.env, id);
  // 201 when the file is new, 200 when it was replaced. Both are success to an agent reading a
  // status class; a WebDAV client reads the exact code and expects this distinction.
  // 新建回 201,覆盖回 200。对一个只看状态码大类的代理,两者都是成功;
  // 而 WebDAV 客户端读的是确切的码,它等着这个区分。
  const done = txt('ok', clash ? 200 : 201);
  // The version just made, handed back on the spot. Without it, an agent making a second edit has
  // to fetch the whole file again only to learn a token it could have been told -- and the window
  // between that fetch and its write is exactly the window If-Match exists to close.
  // 刚刚造出的那一版,当场奉还。没有它,一个要做第二次修改的代理就得把整个文件再取一遍,
  // 只为知道一个本可以直接被告知的令牌 —— 而那次取回与它下一次写入之间的空当,
  // 恰恰就是 If-Match 要关掉的那个空当。
  done.headers.set('ETag', `"${versioned ? vid : `${id}-${t}`}"`);
  return done;
});

// ---------- The same link, seen as a WebDAV volume ----------
// ---------- 同一条链接,当作 WebDAV 卷来看 ----------
//
// The plain-text face above is for a program that was handed a URL. This face is for everything
// that already knows how to mount one: rclone, Cyberduck, Finder, Explorer. Same URL, same
// permissions, same paths -- only the grammar differs, and which grammar you get is decided by
// the method you send.
//
// It is deliberately NOT what the instructions describe. A PROPFIND listing of two entries is
// about 1.2 KB of XML where the plain listing is 21 bytes; telling an agent to speak WebDAV
// would spend eighty times the tokens on the one call it makes most, to reach the same rows.
// So the model reads lines and a person mounts a volume, and neither pays for the other.
//
// 上面那副纯文本的面孔,是给"拿到一个 URL 的程序"用的。这副面孔是给一切早就会挂载的东西用的:
// rclone、Cyberduck、Finder、资源管理器。同一个 URL、同一套权限、同一批路径 ——
// 差别只在语法,而你得到哪种语法,由你发的方法决定。
//
// 它刻意不是那份指令所描述的东西。两个条目的 PROPFIND 列表约 1.2 KB XML,
// 而纯文本列表是 21 字节;让代理去讲 WebDAV,等于在它调用最频繁的那个动作上花八十倍的 token,
// 换回同样几行。于是模型读行,人挂卷,谁也不替谁付账。

const DAV_METHODS = new Set(['OPTIONS', 'PROPFIND', 'PROPPATCH', 'MKCOL', 'MOVE', 'COPY', 'LOCK', 'UNLOCK']);
/** Ceiling on a lock's life. The holder proves it is still there by refreshing; this is how long
 *  after a client vanishes -- crash, sleep, cable out -- its locks survive it.
 *  一把锁的寿命上限。持有者靠续租证明自己还在;客户端消失之后(崩溃、休眠、拔线),
 *  它的锁最多再活这么久。 */
const DAV_LOCK_MAX_S = 600;
const DAV_COPY_MAX_NODES = 200;

const xesc = (s: string) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&apos;');

const xml = (body: string, status = 207) =>
  new Response(`<?xml version="1.0" encoding="utf-8"?>\n${body}`, {
    status,
    headers: { 'Content-Type': 'application/xml; charset=utf-8', 'X-Content-Type-Options': 'nosniff' },
  });

/** Where a path lives in URL space. Collections carry the trailing slash clients rely on to tell
 *  a folder from a file without asking again.
 *  一条路径在 URL 空间里的位置。目录带上尾斜杠 —— 客户端靠它区分目录与文件,不必再问一次。 */
const davHref = (token: string, segs: string[], coll: boolean) =>
  `/agt/${token}/` + segs.map(encodeURIComponent).join('/') + (coll && segs.length ? '/' : '');

/** One <response> block. The property set is fixed rather than following the request: every
 *  client asks for some subset of these, extras are ignored, and choosing per request would
 *  mean parsing the body to learn nothing that changes the answer.
 *  一个 <response> 块。属性集是固定的,不跟着请求走:每个客户端要的都是其中一个子集,
 *  多给的会被忽略;按请求裁剪意味着解析请求体,却问不出任何能改变答案的东西。 */
function davEntry(token: string, segs: string[], n: NodeRow | null): string {
  const coll = !n || n.kind === 'folder';
  const t = n?.updated_at || now();
  const name = segs.length ? segs[segs.length - 1] : '';
  return `<D:response><D:href>${xesc(davHref(token, segs, coll))}</D:href><D:propstat><D:prop>`
    + `<D:resourcetype>${coll ? '<D:collection/>' : ''}</D:resourcetype>`
    + `<D:displayname>${xesc(name)}</D:displayname>`
    + `<D:getlastmodified>${new Date(t).toUTCString()}</D:getlastmodified>`
    + `<D:creationdate>${new Date(n?.created_at || t).toISOString()}</D:creationdate>`
    + (coll ? '' : `<D:getcontentlength>${n!.size || 0}</D:getcontentlength>`
      + `<D:getcontenttype>${xesc(n!.mime || 'application/octet-stream')}</D:getcontenttype>`
      + `<D:getetag>"${xesc(etagOf(n!))}"</D:getetag>`)
    + '<D:supportedlock><D:lockentry><D:lockscope><D:exclusive/></D:lockscope>'
    + '<D:locktype><D:write/></D:locktype></D:lockentry></D:supportedlock>'
    + '<D:lockdiscovery/>'
    + '</D:prop><D:status>HTTP/1.1 200 OK</D:status></D:propstat></D:response>';
}

/** The live lock standing in the way of writing at `path`, if any -- its own, or one taken over a
 *  folder above it with depth infinity. Expiry is applied here rather than swept, so a lapsed
 *  lock stops blocking at the instant it lapses and not at the next cleanup.
 *  挡在"写 path"前面的那把有效的锁 —— 它自己的,或者上层某个目录上带 infinity 深度的那把。
 *  过期在这里判定而不靠清扫,于是失效的锁在失效那一刻就不再拦人,而不是等下一次清理。 */
async function davLockAt(env: Env, shareId: string, path: string): Promise<any | null> {
  const anc: string[] = [''];
  const parts = path ? path.split('/') : [];
  for (let i = 1; i <= parts.length; i++) anc.push(parts.slice(0, i).join('/'));
  const ph = anc.map((_, i) => `?${i + 3}`).join(',');
  const row = await env.DB.prepare(
    `SELECT * FROM drive_dav_locks
      WHERE share_id=?1 AND expires_at>?2 AND path IN (${ph})
        AND (path=?${anc.length + 3} OR depth=1)
      LIMIT 1`
  ).bind(shareId, now(), ...anc, path).first();
  return row || null;
}

/** The lock tokens the caller claims to hold. The If header has a small grammar of its own; the
 *  only part that decides anything here is which tokens it names, so that is all that is read.
 *  调用者声称持有的锁令牌。If 头自有一套小语法,而在这里唯一能决定什么的只是它点了哪些令牌,
 *  所以只读这一点。 */
const davHeld = (c: any): Set<string> =>
  new Set((String(c.req.header('If') || '').match(/opaquelocktoken:[0-9a-fA-F-]+/g) || []));

/** 423 when someone else holds the path, null when the way is clear.
 *  别人占着这条路径就回 423,路通就返回 null。 */
async function davBlocked(c: any, share: any, segs: string[]): Promise<Response | null> {
  const lock = await davLockAt(c.env, share.id, segs.join('/'));
  if (!lock || davHeld(c).has(lock.token)) return null;
  return txt('locked, try again shortly', 423);
}

async function davMkcol(c: any, share: any, roots: Map<string, NodeRow>, segs: string[]): Promise<Response> {
  if (!segs.length) return txt('the top level is fixed', 403);
  if (await agentWalk(c.env, roots, segs)) return txt('already exists', 405);
  const parent = segs.length > 1 ? await agentWalk(c.env, roots, segs.slice(0, -1)) : null;
  if (!parent) return txt(segs.length > 1 ? 'no such folder' : 'the top level is fixed', segs.length > 1 ? 409 : 403);
  if (parent.kind !== 'folder') return txt('not a folder', 409);
  if ((await c.req.text()).trim()) return txt('body not supported', 415);
  let name: string;
  try {
    name = cleanName(segs[segs.length - 1]);
  } catch {
    return txt('bad name', 400);
  }
  const chain = await chainOf(c.env, parent.id);
  if (chain.length >= DEPTH_MAX - 1) return txt('too deep', 403);
  const t = now();
  await c.env.DB.prepare(
    `INSERT INTO drive_nodes (id, owner_id, parent_id, kind, name, created_at, updated_at)
     VALUES (?1,?2,?3,'folder',?4,?5,?5)`
  ).bind(uid(), parent.owner_id, parent.id, name, t).run();
  return txt('', 201);
}

/** Where a Destination header points, in this link's own terms. Anything outside the link is
 *  refused rather than followed: the header is a URL, and a URL can name any server there is.
 *  Destination 头指向何处 —— 按本链接自己的说法。指到链接之外的一律拒绝而不是跟过去:
 *  那个头是一个 URL,而 URL 可以指向世上任何一台服务器。 */
function davDest(c: any, token: string): { segs: string[] } | null {
  const raw = c.req.header('Destination');
  if (!raw) return null;
  let path: string;
  try {
    path = new URL(raw, c.req.url).pathname;
  } catch {
    return null;
  }
  const parts = path.split('/').slice(2);
  if ((parts.shift() || '') !== token) return null;
  if (parts.length && parts[parts.length - 1] === '') parts.pop();
  if (parts.some((s) => s === '')) return null;
  try {
    const segs = parts.map((s) => decodeURIComponent(s));
    if (segs.some((s) => s === '.' || s === '..')) return null;
    return { segs };
  } catch {
    return null;
  }
}

/** Resolve the parent and name a MOVE or COPY is aiming at, and clear whatever sits there.
 *  解析 MOVE / COPY 的目标父目录与名字,并清掉占位的东西。 */
async function davTarget(c: any, share: any, roots: Map<string, NodeRow>, dest: string[], kind: string):
Promise<{ parent: NodeRow; name: string; into: NodeRow | null } | Response> {
  if (dest.length < 2) return txt('the top level is fixed', 403);
  const parent = await agentWalk(c.env, roots, dest.slice(0, -1));
  if (!parent) return txt('no such folder', 409);
  if (parent.kind !== 'folder') return txt('not a folder', 409);
  let name: string;
  try {
    name = cleanName(dest[dest.length - 1]);
  } catch {
    return txt('bad name', 400);
  }
  const clash = await findClash(c.env, parent.owner_id, parent.id, name, kind);
  if (clash) {
    if (c.req.header('Overwrite') === 'F') return txt('already exists', 412);
    // How a desktop application saves: write a temporary name, then MOVE it onto the real one. If
    // the real one keeps history, sweeping it into the trash here would end that history and start
    // a brand-new file wearing its name -- and the person who pressed Save would have destroyed
    // the very thing they were being careful about. So the arriving bytes are folded in as the
    // next version instead, which is what they thought was happening all along.
    // 桌面软件就是这么保存的:先写一个临时名字,再 MOVE 到真名上。如果真名那个保留着历史,
    // 在这里把它扫进回收站,就等于终结那段历史,并让一个全新的文件顶着它的名字重新开始 ——
    // 而按下保存的那个人,亲手毁掉的正是他一直在小心保全的东西。
    // 所以到来的字节改为并入它、成为下一版,而这本来就是他以为正在发生的事。
    if (clash.kind === 'file' && clash.versioned) return { parent, name, into: clash };
    const stmts = [c.env.DB.prepare('UPDATE drive_nodes SET trashed=1, trashed_at=?1, updated_at=?1 WHERE id=?2')
      .bind(now(), clash.id)];
    const ad = ancDelta(c.env, clash.parent_id, -nodeBytes(clash));
    if (ad) stmts.push(ad);
    await c.env.DB.batch(stmts);
  }
  return { parent, name, into: null };
}

/** Fold a moved file's bytes into the versioned file it landed on. The source row disappears and
 *  its bytes do not travel: they simply become the target's current version. However large the
 *  file, this costs one row and copies nothing.
 *  把被移动文件的字节并入它落到的那个保留历史的文件。源那一行消失,而它的字节并不旅行:
 *  它们直接成为目标的当前版本。文件再大,这里也只花一行记录,一个字节都不拷贝。 */
async function davSpliceMove(c: any, src: NodeRow, into: NodeRow): Promise<Response> {
  if (src.kind !== 'file' || !src.r2_key) return txt('not a file', 400);
  const base = namedBase(c);
  if (base && base !== etagOf(into)) return txt('stale base, re-read the file first', 412);
  const head = await headVersion(c.env, into);
  const t = now();
  const vid = uid();
  const size = src.size || 0;
  const mime = src.mime || into.mime || '';
  // A temporary file born under a folder that keeps history has a small history of its own, and it
  // is about to stop existing. Its current bytes live on as the target's version; the rest of what
  // it remembered has nowhere left to be reached from.
  // 一个出生在"保留历史"目录下的临时文件,自己也有一小段历史,而它马上就不存在了。
  // 它当前的字节将作为目标的一版活下去;它记住的其余那些,从此再没有任何路径能够到达。
  const own = await c.env.DB.prepare('SELECT r2_key FROM drive_versions WHERE node_id=?1 AND r2_key<>?2')
    .bind(src.id, src.r2_key).all();
  const dead = ((own.results || []) as any[]).flatMap((r) => [r.r2_key, r.r2_key + THUMB_SUFFIX]);
  if (dead.length) await c.env.RAW.delete(dead).catch(() => {});
  const stmts = [
    versionWrite(c.env, into.id, head, {
      id: vid, key: src.r2_key, size, mime, origin: 'link', author: null, linked: !!base, at: t,
    }),
    // The thumbnail travels with the bytes it describes -- it sits beside them, and they did not move.
    // 缩略图随它所描述的字节一同前往 —— 它就在那些字节旁边,而那些字节并没有动。
    c.env.DB.prepare(
      'UPDATE drive_nodes SET r2_key=?1, size=?2, mime=?3, ver_head=?4, has_thumb=?5, updated_at=?6 WHERE id=?7'
    ).bind(src.r2_key, size, mime, vid, src.has_thumb ? 1 : 0, t, into.id),
    c.env.DB.prepare('DELETE FROM drive_versions WHERE node_id=?1').bind(src.id),
    c.env.DB.prepare('DELETE FROM drive_nodes WHERE id=?1').bind(src.id),
    // Only the target's previous live bytes stop counting. The arriving ones were already counted
    // under the source and merely changed owner within the same drive; history is charged to nobody.
    // 只有目标从前那份"在用的"字节不再计数。到来的那份本就记在源头上,
    // 只是在同一个网盘里换了归属;而历史不记在任何人头上。
    c.env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes-?1,0) WHERE id=?2')
      .bind(into.size || 0, into.owner_id),
  ];
  const out = ancDelta(c.env, src.parent_id, -size);
  const back = ancDelta(c.env, into.parent_id, size - (into.size || 0));
  if (out) stmts.push(out);
  if (back) stmts.push(back);
  await c.env.DB.batch(stmts);
  await pruneVersions(c.env, into.id);
  return txt('', 204);
}

async function davMove(c: any, share: any, roots: Map<string, NodeRow>, node: NodeRow | null, token: string): Promise<Response> {
  if (!node) return txt('no such path', 404);
  const dest = davDest(c, token);
  if (!dest) return txt('bad destination', 400);
  const t = await davTarget(c, share, roots, dest.segs, node.kind);
  if (t instanceof Response) return t;
  if (t.into) return davSpliceMove(c, node, t.into);
  // A folder cannot be moved inside itself: the subtree would leave the tree entirely, taking
  // its bytes and every node in it out of reach of any walk from the root.
  // 目录不能移进自己里面:那棵子树会整个脱离这棵树,连同它的字节和其中每个节点,
  // 从根出发的任何遍历都再也够不到。
  const chain = await chainOf(c.env, t.parent.id);
  if (chain.some((n) => n.id === node.id)) return txt('cannot move a folder into itself', 409);
  const moved = t.parent.id !== node.parent_id;
  const stmts = [c.env.DB.prepare('UPDATE drive_nodes SET parent_id=?1, name=?2, updated_at=?3 WHERE id=?4')
    .bind(t.parent.id, t.name, now(), node.id)];
  if (moved) {
    const out = ancDelta(c.env, node.parent_id, -nodeBytes(node));
    const into = ancDelta(c.env, t.parent.id, nodeBytes(node));
    if (out) stmts.push(out);
    if (into) stmts.push(into);
  }
  await c.env.DB.batch(stmts);
  return txt('', 204);
}

/** Copy a node, and everything under it if it is a folder. Bytes are re-uploaded rather than
 *  referenced: two drive entries pointing at one R2 object would make deleting either one
 *  destroy both. Bounded, because an unbounded recursion here is one request against a whole
 *  subtree and would run out of CPU somewhere in the middle, leaving half a copy.
 *  复制一个节点,是目录就连同其下的一切。字节是重新写一份而不是引用:
 *  两条网盘记录指向同一个 R2 对象,会让删掉任何一条都毁掉两条。
 *  有上限 —— 这里若无限递归,一次请求要对付整棵子树,中途耗尽 CPU,只留下半份副本。 */
async function davCopyTree(env: Env, src: NodeRow, parentId: string, name: string, ownerId: string, budget: { n: number; bytes: number }, versioned: boolean): Promise<void> {
  if (--budget.n < 0) throw new HttpError(507, 'e_drive_quota');
  const t = now();
  const id = uid();
  if (src.kind === 'folder') {
    // The copy of a folder does not inherit the original's policy, and the copy of a file does not
    // inherit its history. A copy is a new file that merely happens to start out holding the same
    // bytes; what governs it from here is where it landed, not where it was taken from.
    // 目录的副本不继承原目录的策略,文件的副本也不继承它的历史。
    // 副本是一个恰好以相同字节开头的新文件;从此刻起管着它的是它落在了哪儿,而不是它取自何处。
    await env.DB.prepare(
      `INSERT INTO drive_nodes (id, owner_id, parent_id, kind, name, created_at, updated_at)
       VALUES (?1,?2,?3,'folder',?4,?5,?5)`
    ).bind(id, ownerId, parentId, name, t).run();
    const kids = await env.DB.prepare('SELECT * FROM drive_nodes WHERE parent_id=?1 AND trashed=0')
      .bind(src.id).all();
    for (const k of (kids.results || []) as unknown as NodeRow[]) {
      await davCopyTree(env, k, id, k.name, ownerId, budget, versioned);
    }
    return;
  }
  budget.bytes -= src.size || 0;
  if (budget.bytes < 0) throw new HttpError(507, 'e_drive_quota');
  const key = `drive/${ownerId}/${id}`;
  if (src.r2_key) {
    const obj: any = await env.RAW.get(src.r2_key);
    if (obj) await env.RAW.put(key, obj.body, { httpMetadata: { contentType: src.mime || 'application/octet-stream' } });
  }
  const vid = uid();
  const stmts = [
    env.DB.prepare(
      `INSERT INTO drive_nodes (id, owner_id, parent_id, kind, name, mime, size, r2_key, versioned, ver_head, created_at, updated_at)
       VALUES (?1,?2,?3,'file',?4,?5,?6,?7,?8,?9,?10,?10)`
    ).bind(id, ownerId, parentId, name, src.mime || '', src.size || 0, key,
      versioned ? 1 : 0, versioned ? vid : null, t),
    env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes+?1,0) WHERE id=?2').bind(src.size || 0, ownerId),
  ];
  if (versioned) {
    stmts.push(versionWrite(env, id, null, {
      id: vid, key, size: src.size || 0, mime: src.mime || '', origin: 'link', author: null, linked: false, at: t,
    }));
  }
  await env.DB.batch(stmts);
}

async function davCopy(c: any, share: any, roots: Map<string, NodeRow>, node: NodeRow | null, token: string): Promise<Response> {
  if (!node) return txt('no such path', 404);
  const dest = davDest(c, token);
  if (!dest) return txt('bad destination', 400);
  const t = await davTarget(c, share, roots, dest.segs, node.kind);
  if (t instanceof Response) return t;
  const chain = await chainOf(c.env, t.parent.id);
  if (chain.some((n) => n.id === node.id)) return txt('cannot copy a folder into itself', 409);
  const q = await driveQuota(c.env, t.parent.owner_id);
  if (!q.enabled) return txt('drive disabled', 403);
  // Copying onto a file that keeps history is the same event as moving onto one -- something
  // arrives wearing that name -- so it ends the same way: a new version, not a new file standing
  // where the old one used to be.
  // 复制到一个保留历史的文件上,与移动到它上面是同一件事 —— 有东西顶着那个名字到来 ——
  // 所以结局也一样:多出一个版本,而不是多出一个站在旧文件位置上的新文件。
  if (t.into) {
    if (node.kind !== 'file' || !node.r2_key) return txt('not a file', 400);
    const src: any = await c.env.RAW.get(node.r2_key);
    if (!src) return txt('no such path', 404);
    const size = node.size || 0;
    if (q.used - (t.into.size || 0) + size > q.quota) return txt('out of space', 507);
    const head = await headVersion(c.env, t.into);
    const at = now();
    const vid = uid();
    const key = `drive/${t.into.owner_id}/${t.into.id}.v${vid}`;
    const mime = node.mime || t.into.mime || '';
    await c.env.RAW.put(key, src.body, { httpMetadata: { contentType: mime || 'application/octet-stream' } });
    const stmts = [
      versionWrite(c.env, t.into.id, head, {
        id: vid, key, size, mime, origin: 'link', author: null, linked: false, at,
      }),
      c.env.DB.prepare(
        'UPDATE drive_nodes SET r2_key=?1, size=?2, mime=?3, ver_head=?4, has_thumb=0, updated_at=?5 WHERE id=?6'
      ).bind(key, size, mime, vid, at, t.into.id),
      c.env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes+?1,0) WHERE id=?2')
        .bind(size - (t.into.size || 0), t.into.owner_id),
    ];
    const back = ancDelta(c.env, t.into.parent_id, size - (t.into.size || 0));
    if (back) stmts.push(back);
    await c.env.DB.batch(stmts);
    await pruneVersions(c.env, t.into.id);
    return txt('', 204);
  }
  const budget = { n: DAV_COPY_MAX_NODES, bytes: q.quota - q.used };
  try {
    await davCopyTree(c.env, node, t.parent.id, t.name, t.parent.owner_id, budget,
      chain.some((x) => x.ver_policy));
  } catch {
    return txt('too large to copy here', 507);
  }
  const ad = ancDelta(c.env, t.parent.id, nodeBytes(node));
  if (ad) await ad.run();
  return txt('', 201);
}

/** Grant or refresh a write lock. Not a formality: it is stored, it blocks the next writer, and
 *  it dies on a clock -- which is the only thing that can free it when the holder never comes
 *  back to say it is done.
 *  发一把写锁,或给已有的续期。这不是走过场:它被存下来、会挡住下一个写者、并且靠时钟死亡 ——
 *  当持有者再也没回来说一声"我完事了",能放开它的只有时钟。 */
async function davLock(c: any, share: any, segs: string[]): Promise<Response> {
  const path = segs.join('/');
  const secs = (() => {
    const m = /Second-(\d+)/i.exec(String(c.req.header('Timeout') || ''));
    return Math.min(m ? parseInt(m[1], 10) : DAV_LOCK_MAX_S, DAV_LOCK_MAX_S);
  })();
  const held = davLockAt(c.env, share.id, path);
  const existing = await held;
  const mine = existing && davHeld(c).has(existing.token);
  if (existing && !mine) return txt('locked, try again shortly', 423);
  const body = await c.req.text();
  const ownerTag = (/<[^>]*owner[^>]*>([\s\S]*?)<\/[^>]*owner>/i.exec(body) || ['', ''])[1].slice(0, 400);
  const depth = String(c.req.header('Depth') || '0').toLowerCase() === 'infinity' ? 1 : 0;
  const t = now();
  const tok = existing ? existing.token : `opaquelocktoken:${uid()}`;
  if (existing) {
    await c.env.DB.prepare('UPDATE drive_dav_locks SET expires_at=?1 WHERE token=?2')
      .bind(t + secs * 1000, tok).run();
  } else {
    await c.env.DB.prepare(
      `INSERT INTO drive_dav_locks (token, share_id, path, depth, owner, expires_at, created_at)
       VALUES (?1,?2,?3,?4,?5,?6,?7)`
    ).bind(tok, share.id, path, depth, ownerTag, t + secs * 1000, t).run();
  }
  const r = xml(
    `<D:prop xmlns:D="DAV:"><D:lockdiscovery><D:activelock>`
    + '<D:locktype><D:write/></D:locktype><D:lockscope><D:exclusive/></D:lockscope>'
    + `<D:depth>${depth ? 'infinity' : '0'}</D:depth>`
    + (ownerTag ? `<D:owner>${ownerTag}</D:owner>` : '')
    + `<D:timeout>Second-${secs}</D:timeout>`
    + `<D:locktoken><D:href>${xesc(tok)}</D:href></D:locktoken>`
    + '</D:activelock></D:lockdiscovery></D:prop>',
    existing ? 200 : 201
  );
  r.headers.set('Lock-Token', `<${tok}>`);
  return r;
}

async function davUnlock(c: any, share: any): Promise<Response> {
  const tok = (String(c.req.header('Lock-Token') || '').match(/opaquelocktoken:[0-9a-fA-F-]+/) || [''])[0];
  if (!tok) return txt('no lock token', 400);
  await c.env.DB.prepare('DELETE FROM drive_dav_locks WHERE token=?1 AND share_id=?2')
    .bind(tok, share.id).run();
  return txt('', 204);
}

async function davPropfind(c: any, share: any, roots: Map<string, NodeRow>, node: NodeRow | null, segs: string[], token: string): Promise<Response> {
  const depth = String(c.req.header('Depth') || '1').toLowerCase();
  // A whole-subtree listing in one answer is how a mount becomes a denial of service against
  // its own server: one request, unbounded rows, unbounded XML.
  // 一次答完整棵子树,正是"挂载把自己的服务器打垮"的方式:一个请求,无上限的行,无上限的 XML。
  if (depth === 'infinity') {
    return xml('<D:error xmlns:D="DAV:"><D:propfind-finite-depth/></D:error>', 403);
  }
  if (segs.length && !node) return txt('no such path', 404);
  const out = [davEntry(token, segs, node)];
  if (depth === '1') {
    if (!segs.length) {
      for (const [seg, n] of roots) out.push(davEntry(token, [seg], n));
    } else if (node!.kind === 'folder') {
      const rows = await c.env.DB.prepare(
        `SELECT * FROM drive_nodes WHERE parent_id=?1 AND trashed=0 ORDER BY kind DESC, name LIMIT ${LIST_LIMIT}`
      ).bind(node!.id).all();
      for (const r of (rows.results || []) as unknown as NodeRow[]) out.push(davEntry(token, [...segs, r.name], r));
    }
  }
  return xml(`<D:multistatus xmlns:D="DAV:">${out.join('')}</D:multistatus>`);
}

/** Every WebDAV verb that is not also a plain-HTTP one. GET, PUT and DELETE are shared with the
 *  text face above -- that sharing is the point, since it is what makes the two faces the same
 *  drive rather than two drives that resemble each other.
 *  所有"不同时也是朴素 HTTP"的 WebDAV 动词。GET、PUT、DELETE 与上面那副文本面孔共用 ——
 *  共用正是要点所在:正因如此,两副面孔才是同一个网盘,而不是两个彼此相像的网盘。 */
async function davHandle(c: any, share: any, roots: Map<string, NodeRow>, node: NodeRow | null, segs: string[], token: string): Promise<Response> {
  const method = c.req.method;
  const rw = share.role === 'editor';
  if (method === 'OPTIONS') {
    const r = txt('', 204);
    // Class 2 is what says "this volume can be written to" to Finder and Explorer; without it
    // they mount read-only, or refuse. A read-only link answers class 1 and means it.
    // 类别 2 就是对 Finder 与资源管理器说"这个卷可以写";没有它,它们要么只读挂载,要么干脆不挂。
    // 只读链接回类别 1,而且说到做到。
    r.headers.set('DAV', rw ? '1, 2' : '1');
    r.headers.set('MS-Author-Via', 'DAV');
    r.headers.set('Allow', rw
      ? 'OPTIONS, HEAD, GET, POST, PUT, DELETE, PROPFIND, PROPPATCH, MKCOL, MOVE, COPY, LOCK, UNLOCK'
      : 'OPTIONS, HEAD, GET, PROPFIND');
    r.headers.set('Accept-Ranges', 'bytes');
    return r;
  }
  if (method === 'PROPFIND') return davPropfind(c, share, roots, node, segs, token);
  if (!rw) return txt('read-only link', 403);
  if (method === 'UNLOCK') return davUnlock(c, share);
  if (method === 'LOCK') return davLock(c, share, segs);
  const blocked = await davBlocked(c, share, segs);
  if (blocked) return blocked;
  if (method === 'PROPPATCH') {
    // Nothing here has properties beyond the ones that come from the file itself, and saying so
    // with a 403 makes Explorer abandon the copy it was in the middle of. Report success for
    // whatever was asked and store none of it: the client wanted to set a timestamp or a Win32
    // attribute bit, and the copy it is actually making matters more than that bit does.
    // 这里的东西除了文件自身带来的属性之外没有别的属性,而用 403 这么说,
    // 会让资源管理器放弃它正在进行的复制。对请求的一切报成功,但一样也不存:
    // 客户端想设的是一个时间戳或 Win32 属性位,而它真正在做的那次复制,比那个位要紧。
    return xml(`<D:multistatus xmlns:D="DAV:"><D:response><D:href>${xesc(davHref(token, segs, !node || node.kind === 'folder'))}</D:href>`
      + '<D:propstat><D:prop/><D:status>HTTP/1.1 200 OK</D:status></D:propstat></D:response></D:multistatus>');
  }
  if (method === 'MKCOL') return davMkcol(c, share, roots, segs);
  if (method === 'MOVE') return davMove(c, share, roots, node, token);
  if (method === 'COPY') return davCopy(c, share, roots, node, token);
  return txt('unsupported method', 405);
}

