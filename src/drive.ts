driveApp.post('/trash/empty', async (c) => {
  const user = c.get('user');
  const rows = await c.env.DB.prepare(
    `SELECT id FROM drive_nodes WHERE owner_id=?1 AND trashed=1 LIMIT ${TRASH_ROOT_SCAN}`
  ).bind(user.id).all();
  const roots = ((rows.results || []) as any[]).map((r) => r.id);
  // Which of these the trash may not take. Asked of the whole trash in one query rather than once
  // per root: somebody who emptied a folder tree has a great many roots, and not one of them is
  // special enough to deserve its own round trip.
  // 这些当中哪些是回收站带不走的。一次问完整个回收站,而不是每个根问一遍:
  // 清掉过一整棵目录树的人,根会有很多,而它们没有哪一个特殊到值得单独跑一趟。
  const kept = new Set<string>();
  if (roots.length) {
    const ph = roots.map((_, i) => '?' + (i + 1)).join(',');
    const hit = await c.env.DB.prepare(
      `WITH RECURSIVE sub(root, id, depth) AS (
         SELECT id, id, 0 FROM drive_nodes WHERE id IN (${ph})
         UNION ALL SELECT s.root, n.id, s.depth+1 FROM drive_nodes n JOIN sub s ON n.parent_id=s.id
           WHERE s.depth<${DEPTH_MAX}
       ) SELECT DISTINCT s.root AS root FROM sub s JOIN drive_nodes n ON n.id=s.id WHERE n.versioned=1`
    ).bind(...roots).all();
    for (const r of (hit.results || []) as any[]) kept.add(r.root);
  }
  const target = roots.find((id) => !kept.has(id));
  if (target) await purgeSubtree(c.env, target);
  const left = await c.env.DB.prepare(
    'SELECT COUNT(*) AS n FROM drive_nodes WHERE owner_id=?1 AND trashed=1'
  ).bind(user.id).first<any>();
  // What is left to do, less what will never be done here. The caller loops on `remaining`, so
  // counting the untouchable ones into it would leave it spinning against files it is not allowed
  // to remove, forever making the same request and getting the same answer.
  // 还剩多少要做,减去在这里永远做不成的那些。调用方靠 remaining 循环,
  // 若把动不得的那些算进去,它就会对着自己无权移除的文件空转 —— 一遍遍发同一个请求,
  // 一遍遍得到同一个答复。
  return c.json({ remaining: Math.max((left?.n || 0) - kept.size, 0), kept: kept.size });
});

