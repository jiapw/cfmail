driveApp.post('/nodes/:id/move', async (c) => {
  const a = await accessNode(c, c.req.param('id'), 'edit');
  if (a.chain.some((n) => n.trashed)) throw new HttpError(400, 'e_drive_trashed');
  if (a.level !== 'owner' && a.node.id === a.shareRoot) throw new HttpError(403, 'e_drive_forbidden');
  const parent = String((await c.req.json<any>()).parent || 'root');
  let parentId: string | null;
  if (parent === 'root') {
    // Only the owner has a root here; an editor's own root is a different drive
    // 根目录只属于所有者;编辑者的根是另一个人的网盘
    if (a.level !== 'owner') throw new HttpError(403, 'e_drive_forbidden');
    parentId = null;
  } else {
    const t = await accessNode(c, parent, 'edit');
    if (t.node.kind !== 'folder') throw new HttpError(400, 'e_drive_not_folder');
    if (t.chain.some((n) => n.trashed)) throw new HttpError(400, 'e_drive_trashed');
    // No ownership transfer: source and target must live in the same drive
    // 不做所有权转移:源与目标必须在同一个人的网盘里
    if (t.node.owner_id !== a.node.owner_id) throw new HttpError(400, 'e_drive_cross_drive');
    if (t.chain.some((n) => n.id === a.node.id)) throw new HttpError(400, 'e_drive_cycle');
    if (t.chain.length + 1 >= DEPTH_MAX) throw new HttpError(400, 'e_drive_too_deep');
    parentId = t.node.id;
  }
  // The destination must not already hold this name / 目的地不能已有同名条目
  const clash = await findClash(c.env, a.node.owner_id, parentId, a.node.name, a.node.kind);
  if (clash && clash.id !== a.node.id) throw new HttpError(409, 'e_drive_name_taken');
  {
    const stmts = [
      c.env.DB.prepare('UPDATE drive_nodes SET parent_id=?1, updated_at=?2 WHERE id=?3')
        .bind(parentId, now(), a.node.id),
    ];
    // Old chain loses the bytes, new chain gains them; a shared prefix nets to zero by itself
    // 旧链减、新链加。公共前缀一减一加自动归零,无需特判
    if (parentId !== a.node.parent_id) {
      const bytes = nodeBytes(a.node);
      const sub = ancDelta(c.env, a.node.parent_id, -bytes);
      const add = ancDelta(c.env, parentId, bytes);
      if (sub) stmts.push(sub);
      if (add) stmts.push(add);
    }
    await c.env.DB.batch(stmts);
  }
  return c.json({ ok: true });
});

