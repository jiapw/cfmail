/** A folder's address: its ancestors and itself, root first. The Drive root is not in it -- it
 *  has no row, and every path implicitly starts there.
 *  一个文件夹的地址:自根而下的祖先加它自己。网盘根不在其中 —— 它没有行,而每条路径都从那里起步。 */
type FolderPath = { id: string; name: string }[];

/** The node and all its ancestors, node first, root last. Empty when the id does not exist.
 *  节点及其全部祖先,节点在前、根在后。id 不存在时为空。 */
async function chainOf(env: Env, nodeId: string): Promise<NodeRow[]> {
  const rows = await env.DB.prepare(
    `WITH RECURSIVE chain AS (
       SELECT n.*, 0 AS depth FROM drive_nodes n WHERE n.id=?1
       UNION ALL
       SELECT p.*, c.depth+1 FROM drive_nodes p JOIN chain c ON p.id=c.parent_id WHERE c.depth<${DEPTH_MAX}
     ) SELECT * FROM chain ORDER BY depth`
  ).bind(nodeId).all();
  return (rows.results || []) as unknown as NodeRow[];
}

interface Access {
  node: NodeRow;
  level: 'owner' | 'editor' | 'viewer';
  /** For share members, the highest shared ancestor -- their movements stay inside this subtree.
   *  共享成员可见范围的顶点 —— 他们的一切操作都被圈在这棵子树里。 */
  shareRoot: string | null;
  chain: NodeRow[];
  /** Whether some share along the way carries the meeting pen. It is not a level of access to the
   *  file -- see migration 0035 -- so it rides beside `level` rather than inside it, and every
   *  existing test of `level` goes on meaning exactly what it meant.
   *  沿途是否有某条共享带着那支会议的笔。它不是对文件的权限档次(见 0035 迁移),
   *  所以它与 level 并列而不住在里面 —— 现有每一处对 level 的判断,含义分毫未变。 */
  meet: boolean;
}

/** Resolve what the current user may do with a node. Owners always pass (even in the trash);
 *  others need a share membership on some ancestor, and anything inside the owner's trash is
 *  invisible to them. Missing and forbidden both answer 404, to not leak existence.
 *  解析当前用户对节点的权限。所有者永远放行(含回收站);其他人需要在某个祖先上有共享成员资格,
 *  且所有者回收站里的内容对他们一律不可见。不存在与无权限统一回 404,不泄露存在性。 */
async function accessNode(c: any, nodeId: string, need: 'view' | 'edit' | 'owner'): Promise<Access> {
  const user: User = c.get('user');
  const chain = await chainOf(c.env, nodeId);
  if (!chain.length) throw new HttpError(404, 'e_drive_not_found');
  const node = chain[0];
  if (node.owner_id === user.id) return { node, level: 'owner', shareRoot: null, chain, meet: true };
  if (need === 'owner') throw new HttpError(404, 'e_drive_not_found');
  if (chain.some((n) => n.trashed)) throw new HttpError(404, 'e_drive_not_found');
  const ids = chain.map((n) => n.id);
  // A share qualifies only if it is alive (not revoked, not expired), this user has actually
  // joined it, and -- when it names a domain -- they hold a mailbox under that domain. The
  // domain test is the department check: membership follows the mailbox, so someone who joins
  // the department later gains access without the share being touched.
  //
  // Public shares reach this query too, but only through a membership row, which exists solely
  // because a signed-in visitor pressed "add to my drive" on the landing page. The link itself
  // still needs no account and grants nothing here; and whatever the row says, a public share
  // is read-only -- the role is pinned at creation, refused on update, and pinned again below
  // so a single wrong row could never hand out write access.
  //
  // 一条共享要生效,必须仍然活着(未撤销、未过期)、本用户确实加入过它,并且 —— 若它指定了
  // 域名 —— 他在该域名下持有信箱。这个域名判定就是部门校验:资格随信箱走,
  // 后来加入该部门的人无需改动共享即可获得访问权。
  //
  // 公开分享也会走到这条查询,但只能经由一条成员记录进来,而那条记录的唯一来源是某个已登录
  // 的访问者在落地页上按了"添加到我的网盘"。链接本身仍然无需账号,且在此不授予任何东西;
  // 并且无论那行怎么写,公开分享一律只读 —— 角色在创建时钉死、更新时被拒,下面再钉一次,
  // 单独一行写错也绝无可能发出写权限。
  const rows = await c.env.DB.prepare(
    `SELECT si.node_id,
            CASE WHEN s.audience='public' THEN 'viewer' ELSE s.role END AS role,
            s.meet AS meet
       FROM drive_shares s
       JOIN drive_share_items si ON si.share_id = s.id
       JOIN drive_share_members m ON m.share_id = s.id
     WHERE m.user_id=?1 AND s.audience IN ('internal','public')
       AND s.revoked_at IS NULL AND (s.expires_at IS NULL OR s.expires_at > ?2)
       AND (s.domain_id IS NULL OR EXISTS (
         SELECT 1 FROM grants g JOIN mailboxes mb ON mb.id=g.mailbox_id
          WHERE g.user_id=?1 AND mb.domain_id = s.domain_id))
       AND si.node_id IN (${ids.map((_, i) => '?' + (i + 3)).join(',')})`
  ).bind(user.id, now(), ...ids).all();
  const hits = (rows.results || []) as { node_id: string; role: string; meet: number }[];
  if (!hits.length) throw new HttpError(404, 'e_drive_not_found');
  const level = hits.some((h) => h.role === 'editor') ? 'editor' : 'viewer';
  if (need === 'edit' && level !== 'editor') throw new HttpError(403, 'e_drive_forbidden');
  // Among qualifying shares pick the one closest to the root: the widest subtree
  // 命中多个共享时取离根最近的那个:活动范围最大
  const best = hits
    .filter((h) => level === 'viewer' || h.role === 'editor')
    .sort((a, b) => ids.indexOf(b.node_id) - ids.indexOf(a.node_id))[0];
  return { node, level, shareRoot: best.node_id, chain, meet: hits.some((h) => !!h.meet) };
}

function cleanName(v: unknown): string {
  // Control characters and '/' out; everything else (any script) is welcome
  // 去掉控制字符与 '/',其余(任意文字)都放行
  const s = String(v ?? '').replace(/[\u0000-\u001f\u007f/]/g, '').trim();
  if (!s || s.length > NAME_MAX) throw new HttpError(400, 'e_drive_bad_name');
  return s;
}

/** A content digest as the client claims it: 64 hex characters or nothing at all. Shape is all
 *  that is checked here -- whether it is TRUE is settled by R2, which is handed the same string as
 *  the expected sha256 of the body and refuses the write if the bytes disagree.
 *  客户端声称的内容摘要:要么 64 个十六进制字符,要么什么都没有。这里只查形状 ——
 *  它是否"为真"由 R2 判定:同一个字符串作为请求体的预期 sha256 交给它,字节对不上就拒绝写入。 */
function cleanHash(v: unknown): string {
  const s = String(v ?? '').trim().toLowerCase();
  return /^[0-9a-f]{64}$/.test(s) ? s : '';
}

function cleanMime(v: unknown): string {
  const s = String(v ?? '').toLowerCase().split(';')[0].trim();
  return /^[a-z0-9.+-]+\/[a-z0-9.+-]+$/.test(s) ? s.slice(0, 120) : 'application/octet-stream';
}

/** The two facts a listing tells about a file's history, asked only where there is history to
 *  tell about. Gated on ver_head, so an ordinary file pays nothing for a pair of columns whose
 *  answer would always have been zero -- and a listing is the one query in this system that runs
 *  a thousand rows at a time.
 *  一个列表要讲的关于文件历史的两件事,只在确有历史可讲的地方问。
 *  以 ver_head 为闸,于是普通文件不必为一对答案恒为零的列付账 ——
 *  而列表恰恰是这套系统里唯一一个动辄一千行的查询。 */
const VER_COLS = `,
     CASE WHEN n.ver_head IS NULL THEN 0
       ELSE (SELECT COUNT(*) FROM drive_versions v WHERE v.node_id=n.id) END AS ver_count,
     CASE WHEN n.ver_head IS NULL THEN NULL
       ELSE (SELECT MIN(v.created_at) FROM drive_versions v WHERE v.node_id=n.id) END AS ver_first,
     (SELECT v.hash FROM drive_versions v WHERE v.id=n.ver_head) AS ver_hash`;

