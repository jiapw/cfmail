// Drive: Google-Drive-like per-user cloud storage. Bytes live in R2 under a key the node points at
// (drive/<owner_id>/<file_id>, and drive/<owner_id>/<file_id>.v<version_id> for the ones a
// versioned file left behind); the folder tree is D1 metadata (drive_nodes), so rename/move never
// copies data (R2 has no rename).
// The switch is per domain; a user has Drive when any of their domains enables it, and the storage
// pool is one per user across domains. Quota: per-user override, else the largest default among the
// user's enabled domains, hard-capped at 10 GB. Sharing: one link per folder, viewer/editor, only for
// signed-in users sharing at least one domain with the owner.
//
// 网盘:Google Drive 风格的每用户云存储。字节存 R2 的 drive/<owner_id>/<file_id>;
// 目录树是 D1 元数据(drive_nodes),改名/移动不搬数据(R2 没有重命名)。
// 开关按域名;用户所属任一域名开启即可用,存储跨域名同一份。
// 配额:用户单独指定优先,否则取其已开启域名中最大的默认值,硬顶 10TB。
// 共享:每文件夹一条链接,查看者/编辑者两档,仅限与所有者至少同属一个域名的登录用户。
//
// Versioning is opt-in per file, and it changes one rule: such a file never overwrites its own
// bytes. Each write lands on a key of its own and the node's pointer moves, so earlier versions
// stay where they already were -- history costs a row, and moving a file is still a parent_id. A
// folder can carry the policy that files born beneath it inherit at creation, read from the
// ancestor chain once, at birth. Copies take bytes but never history: what governs a copy is where
// it landed.
//
// What this is not is a backup. It records what a file has been, in order; it does not offer to
// put the file back. Reading an older version and writing it forward is an ordinary write, and it
// leaves an ordinary version behind -- there is no move here that rewinds anything.
//
// A write may name the version it believes it is replacing (If-Match, or ?base=). Naming a stale
// one is refused with 412. Naming none is allowed -- it is what a mounted volume does all day --
// and is recorded as a cut in the chain, because "written by someone who never saw the version
// before it" is the fact a person needs when two devices disagree, and it cannot be recovered
// afterwards from timestamps. History leaves by expiry alone: a versioned file cannot be
// permanently deleted by hand, only trashed and waited out.
//
// 版本按文件开启,它只改一条规则:这样的文件从不覆盖自己的字节。每次写入落到它自己的键上,
// 节点的指针再移过去,于是更早的版本仍待在原地 —— 保留历史花一行记录,
// 而移动文件依旧只是一个 parent_id。文件夹可以带一条策略,由其下新生的文件在创建时继承,
// 只在出生那一刻从祖先链上读一次。副本带走字节,但从不带走历史:管着副本的是它落在了哪儿。
//
// 它不是备份。它记录一个文件曾经是什么、以什么顺序;它不承诺把文件放回去。
// 读一个旧版本、再把它写回去,是一次寻常的写入,也就留下一个寻常的版本 ——
// 这里没有哪个动作能倒带。
//
// 一次写入可以指认它自以为正在替换的那一版(If-Match,或 ?base=)。指认了过期的那一版,回 412。
// 什么都不指认也放行 —— 挂载的卷整天都这么干 —— 并被记为链条上的一次切断,
// 因为"出自一个从没见过前一版的人之手"正是两台设备打架时人所需要的事实,
// 而它事后无法从时间戳里重建。历史只因过期而离场:保留历史的文件不能被手工彻底删除,
// 只能扔进回收站,然后等。
