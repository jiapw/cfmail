driveApp.post('/upload/:id/complete', async (c) => {
  const u = await getUpload(c);
  const body = await c.req.json<any>();
  const parts = (Array.isArray(body.parts) ? body.parts : [])
    .map((p: any) => ({ partNumber: parseInt(p.n, 10), etag: String(p.etag || '') }))
    .filter((p: any) => Number.isFinite(p.partNumber) && p.etag);
  if (!parts.length) throw new HttpError(400, 'e_bad_request');
  const mpu = c.env.RAW.resumeMultipartUpload(u.r2_key, u.upload_id);
  let obj: R2Object;
  try {
    obj = await mpu.complete(parts);
  } catch (e) {
    await mpu.abort().catch(() => {});
    await c.env.DB.prepare('DELETE FROM drive_uploads WHERE id=?1').bind(u.id).run();
    throw new HttpError(400, 'e_drive_upload_failed');
  }
  // The target folder may have been trashed or purged while the upload ran -- fall back to the root
  // 上传期间目标文件夹可能已进回收站或被删 —— 回落到根目录
  let parentId = u.parent_id;
  let bornVersioned = false;
  if (parentId) {
    const chain = await chainOf(c.env, parentId);
    if (!chain.length || chain.some((x) => x.trashed) || chain[0].owner_id !== u.owner_id || chain[0].kind !== 'folder') {
      parentId = null;
    } else {
      bornVersioned = chain.some((x) => x.ver_policy);
    }
  }
  // Occupied name = overwrite. The node stays -- same id, same star, same creation date -- and
  // only its pointer moves to the bytes this upload just finished writing. Keeping the id is what
  // lets a file that was shared, or that keeps history, survive being replaced.
  // 名字被占用即覆盖。节点留下 —— 同一个 id、同一颗星、同一个创建时间 ——
  // 移动的只是它的指针,指向这次上传刚写完的那份字节。保住 id,才让"被分享过的"
  // 或"保留着历史的"文件,能在一次替换中活下来。
  const clash = await findClash(c.env, u.owner_id, parentId, u.name, 'file');
  const q = await driveQuota(c.env, u.owner_id);
  if (q.used - (clash?.size || 0) + obj.size > q.quota) {
    await c.env.RAW.delete(u.r2_key).catch(() => {});
    await c.env.DB.prepare('DELETE FROM drive_uploads WHERE id=?1').bind(u.id).run();
    throw new HttpError(413, 'e_drive_quota');
  }
  const t = now();
  const author = (c.get('user') as User).id;
  if (clash) {
    const versioned = !!clash.versioned;
    const head = await headVersion(c.env, clash);
    let linked = false;
    try {
      linked = gateBase(c, clash);
    } catch (e) {
      // The parts were already assembled before the base could be checked, so a refusal has to
      // take the finished object away with it -- otherwise a rejected write leaves paid-for bytes
      // in R2 that nothing will ever name.
      // 分片在基准能被检查之前就已经拼装完毕,所以一次拒绝必须把成品一并带走 ——
      // 否则一次被驳回的写入,会在 R2 里留下一份没人再叫得出名字、却照样计费的字节。
      await c.env.RAW.delete(u.r2_key).catch(() => {});
      await c.env.DB.prepare('DELETE FROM drive_uploads WHERE id=?1').bind(u.id).run();
      throw e;
    }
    const vid = uid();
    const stmts = [
      c.env.DB.prepare(
        'UPDATE drive_nodes SET mime=?1, size=?2, r2_key=?3, has_thumb=0, updated_at=?4, ver_head=?5 WHERE id=?6'
      ).bind(u.mime, obj.size, u.r2_key, t, versioned ? vid : clash.ver_head, clash.id),
      c.env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes+?1,0) WHERE id=?2')
        .bind(obj.size - (clash.size || 0), u.owner_id),
      c.env.DB.prepare('DELETE FROM drive_uploads WHERE id=?1').bind(u.id),
    ];
    if (versioned) {
      stmts.push(versionWrite(c.env, clash.id, head, {
        id: vid, key: u.r2_key, size: obj.size, mime: u.mime, origin: 'web', author, linked, at: t,
      }));
    } else if (clash.r2_key) {
      await c.env.RAW.delete([clash.r2_key, clash.r2_key + THUMB_SUFFIX]).catch(() => {});
    }
    // Overwrite replaces bytes under the same parent, so one net delta covers both
    // 覆盖发生在同一父目录下,一条净增量同时涵盖旧去新来
    const ad = ancDelta(c.env, parentId, obj.size - (clash.size || 0));
    if (ad) stmts.push(ad);
    await c.env.DB.batch(stmts);
    if (versioned) await pruneVersions(c.env, clash.id);
    accessCache.delete(author + ':' + clash.id);
    return c.json(nodeJson({
      ...clash, mime: u.mime, size: obj.size, r2_key: u.r2_key, has_thumb: 0, updated_at: t,
      ver_head: versioned ? vid : clash.ver_head,
    }));
  }
  const vid = uid();
  const stmts = [
    c.env.DB.prepare(
      `INSERT INTO drive_nodes (id, owner_id, parent_id, kind, name, mime, size, r2_key, versioned, ver_head, created_at, updated_at)
       VALUES (?1,?2,?3,'file',?4,?5,?6,?7,?8,?9,?10,?10)`
    ).bind(u.id, u.owner_id, parentId, u.name, u.mime, obj.size, u.r2_key,
      bornVersioned ? 1 : 0, bornVersioned ? vid : null, t),
    c.env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes+?1,0) WHERE id=?2')
      .bind(obj.size, u.owner_id),
    c.env.DB.prepare('DELETE FROM drive_uploads WHERE id=?1').bind(u.id),
  ];
  if (bornVersioned) {
    stmts.push(versionWrite(c.env, u.id, null, {
      id: vid, key: u.r2_key, size: obj.size, mime: u.mime, origin: 'web', author, linked: false, at: t,
    }));
  }
  const ad = ancDelta(c.env, parentId, obj.size);
  if (ad) stmts.push(ad);
  await c.env.DB.batch(stmts);
  return c.json(nodeJson({
    id: u.id, parent_id: parentId, kind: 'file', name: u.name, mime: u.mime, size: obj.size,
    versioned: bornVersioned ? 1 : 0, ver_head: bornVersioned ? vid : null, created_at: t, updated_at: t,
  }));
});

