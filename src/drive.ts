/** View access for streaming endpoints, memoised per (user, node) for 60 seconds
 *  流端点的读权限。按用户与节点记忆 60 秒 */
async function accessFileCached(c: any, nodeId: string): Promise<NodeRow> {
  const key = (c.get('user') as User).id + ':' + nodeId;
  const hit = accessCache.get(key);
  if (hit && hit.exp > Date.now()) return hit.node;
  const a = await accessNode(c, nodeId, 'view');
  sweep(accessCache);
  accessCache.set(key, { node: a.node, exp: Date.now() + STREAM_TTL });
  return a.node;
}

