export const driveAdminApp = new Hono<Ctx>();

driveAdminApp.get('/domains', async (c) => {
  const scope = await adminScope(c);
  const rows = await c.env.DB.prepare('SELECT id, name, drive_enabled, drive_quota_mb, drive_share_show_owner FROM domains ORDER BY name').all();
  let list = (rows.results || []) as any[];
  if (scope) list = list.filter((d) => scope.has(d.id));
  return c.json({ domains: list, hard_cap_mb: DRIVE_HARD_CAP_MB });
});

driveAdminApp.post('/domains/:id', async (c) => {
  const id = c.req.param('id');
  await checkDomainScope(c, id);
  const body = await c.req.json<any>();
  const sets: string[] = [];
  const vals: any[] = [];
  if (body.enabled !== undefined) {
    sets.push(`drive_enabled=?${vals.length + 1}`);
    vals.push(body.enabled ? 1 : 0);
  }
  if (body.quota_mb !== undefined) {
    const q = Math.floor(Number(body.quota_mb));
    if (!Number.isFinite(q) || q < 1 || q > DRIVE_HARD_CAP_MB) throw new HttpError(400, 'e_drive_bad_quota');
    sets.push(`drive_quota_mb=?${vals.length + 1}`);
    vals.push(q);
  }
  // Whether a public share link may print the sharer's address. An administrator decision, not
  // the sharer's: it governs what leaves the company, so it cannot sit in the share dialog.
  // 公开分享链接是否可以印出分享者的地址。这是管理员的决定,不是分享者的:
  // 它管的是什么东西流出企业,因此不能放在分享对话框里。
  if (body.share_show_owner !== undefined) {
    sets.push(`drive_share_show_owner=?${vals.length + 1}`);
    vals.push(body.share_show_owner ? 1 : 0);
  }
  if (sets.length) {
    vals.push(id);
    await c.env.DB.prepare(`UPDATE domains SET ${sets.join(',')} WHERE id=?${vals.length}`).bind(...vals).run();
    await audit(c.env, c.get('user'), 'drive.settings', undefined,
      { enabled: body.enabled, quota_mb: body.quota_mb, share_show_owner: body.share_show_owner }, id);
  }
  return c.json({ ok: true });
});

driveAdminApp.get('/users', async (c) => {
  const scope = await adminScope(c);
  const q = String(c.req.query('q') || '').trim().slice(0, 100);
  const binds: any[] = [];
  const where: string[] = [];
  if (scope) {
    const ids = [...scope];
    where.push(`EXISTS (SELECT 1 FROM grants g JOIN mailboxes mb ON mb.id=g.mailbox_id
      WHERE g.user_id=u.id AND mb.domain_id IN (${ids.map((_, i) => '?' + (binds.length + i + 1)).join(',')}))`);
    binds.push(...ids);
  }
  if (q) {
    const like = '%' + q.replace(/[\\%_]/g, (ch) => '\\' + ch) + '%';
    where.push(`(u.email LIKE ?${binds.length + 1} ESCAPE '\\' OR u.name LIKE ?${binds.length + 1} ESCAPE '\\')`);
    binds.push(like);
  }
  const rows = await c.env.DB.prepare(
    `SELECT u.id, u.email, u.name, u.drive_quota_mb AS user_mb, u.drive_bytes AS used,
       (SELECT COUNT(*) FROM drive_nodes n WHERE n.owner_id=u.id AND n.kind='file') AS files,
       (SELECT MAX(d.drive_quota_mb) FROM domains d WHERE d.drive_enabled=1 AND d.id IN
         (SELECT mb2.domain_id FROM grants g2 JOIN mailboxes mb2 ON mb2.id=g2.mailbox_id WHERE g2.user_id=u.id)) AS dom_mb
     FROM users u ${where.length ? 'WHERE ' + where.join(' AND ') : ''}
     ORDER BY used DESC, u.email LIMIT 200`
  ).bind(...binds).all();
  const users = ((rows.results || []) as any[]).map((r) => ({
    id: r.id, email: r.email, name: r.name,
    used: r.used || 0, files: r.files || 0,
    quota_mb: r.user_mb, default_mb: r.dom_mb,
    effective_mb: r.dom_mb == null ? 0 : Math.min(r.user_mb ?? r.dom_mb, DRIVE_HARD_CAP_MB),
    enabled: r.dom_mb != null,
  }));
  return c.json({ users, hard_cap_mb: DRIVE_HARD_CAP_MB });
});

driveAdminApp.post('/users/:id', async (c) => {
  const scope = await adminScope(c);
  const id = c.req.param('id');
  const target = await c.env.DB.prepare('SELECT id, email FROM users WHERE id=?1').bind(id).first<any>();
  if (!target) throw new HttpError(404, 'e_user_not_found');
  if (scope) {
    const ids = [...scope];
    const hit = await c.env.DB.prepare(
      `SELECT 1 AS ok FROM grants g JOIN mailboxes mb ON mb.id=g.mailbox_id
       WHERE g.user_id=?1 AND mb.domain_id IN (${ids.map((_, i) => '?' + (i + 2)).join(',')}) LIMIT 1`
    ).bind(id, ...ids).first();
    if (!hit) throw new HttpError(403, 'e_no_domain_perm');
  }
  const body = await c.req.json<any>();
  let quota: number | null = null;
  if (body.quota_mb !== null && body.quota_mb !== undefined && body.quota_mb !== '') {
    quota = Math.floor(Number(body.quota_mb));
    if (!Number.isFinite(quota) || quota < 1 || quota > DRIVE_HARD_CAP_MB) throw new HttpError(400, 'e_drive_bad_quota');
  }
  await c.env.DB.prepare('UPDATE users SET drive_quota_mb=?1 WHERE id=?2').bind(quota, id).run();
  await audit(c.env, c.get('user'), 'drive.quota', target.email, { quota_mb: quota });
  return c.json({ ok: true });
});

