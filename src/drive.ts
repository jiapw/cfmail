// Small files in one request: raw body, metadata in the query string
// 小文件一次请求:原始字节做 body,元数据放查询串
driveApp.post('/upload', async (c) => {
  const target = await resolveWriteTarget(c, String(c.req.query('parent') || 'root'));
  const name = cleanName(c.req.query('name'));
  const mime = cleanMime(c.req.query('mime'));
  const len = parseInt(c.req.header('Content-Length') || '', 10);
  if (!c.req.raw.body || !Number.isFinite(len) || len < 0) throw new HttpError(400, 'e_drive_body_required');
  if (len > SINGLE_MAX) throw new HttpError(413, 'e_drive_part_too_big');
  // An occupied name means overwrite: same node id, same R2 key, new bytes. The put below
  // replaces the object atomically; star and creation date simply stay.
  // 名字被占用即覆盖。同一节点 id、同一 R2 键、换新字节。下面的 put 原子替换对象,
  // 星标与创建时间自然保留。
  const clash = await findClash(c.env, target.ownerId, target.parentId, name, 'file');
  const oldSize = clash?.size || 0;
  const q0 = await driveQuota(c.env, target.ownerId);
  if (!q0.enabled) throw new HttpError(403, 'e_drive_disabled');
  if (q0.used - oldSize + len > q0.quota) throw new HttpError(413, 'e_drive_quota');
  const id = clash ? clash.id : uid();
  const key = clash?.r2_key || `drive/${target.ownerId}/${id}`;
  const obj = await c.env.RAW.put(key, c.req.raw.body, { httpMetadata: { contentType: mime } });
  const size = obj?.size ?? len;
  const t = now();
  if (clash) {
    // The stale thumbnail dies with the old bytes / 旧缩略图随旧内容一起作废
    await c.env.RAW.delete(key + THUMB_SUFFIX).catch(() => {});
    const stmts = [
      c.env.DB.prepare('UPDATE drive_nodes SET mime=?1, size=?2, has_thumb=0, updated_at=?3 WHERE id=?4')
        .bind(mime, size, t, id),
      c.env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes+?1,0) WHERE id=?2')
        .bind(size - oldSize, target.ownerId),
    ];
    const ad = ancDelta(c.env, target.parentId, size - oldSize);
    if (ad) stmts.push(ad);
    await c.env.DB.batch(stmts);
    return c.json(nodeJson({ ...clash, mime, size, has_thumb: 0, updated_at: t, tree_bytes: clash.tree_bytes }));
  }
  // Re-check with the actual byte count; concurrent uploads may both have passed the pre-check
  // 用实际字节数复核一次;并发上传可能都通过了预检
  const q = await driveQuota(c.env, target.ownerId);
  if (q.used + size > q.quota) {
    await c.env.RAW.delete(key).catch(() => {});
    throw new HttpError(413, 'e_drive_quota');
  }
  {
    const stmts = [
      c.env.DB.prepare(
        `INSERT INTO drive_nodes (id, owner_id, parent_id, kind, name, mime, size, r2_key, created_at, updated_at)
         VALUES (?1,?2,?3,'file',?4,?5,?6,?7,?8,?8)`
      ).bind(id, target.ownerId, target.parentId, name, mime, size, key, t),
      c.env.DB.prepare('UPDATE users SET drive_bytes=drive_bytes+?1 WHERE id=?2').bind(size, target.ownerId),
    ];
    const ad = ancDelta(c.env, target.parentId, size);
    if (ad) stmts.push(ad);
    await c.env.DB.batch(stmts);
  }
  return c.json(nodeJson({ id, parent_id: target.parentId, kind: 'file', name, mime, size, created_at: t, updated_at: t }));
});

// Large files go through R2 multipart. The server keeps the declared size and target on its own
// authority (drive_uploads) instead of trusting the complete call; stale rows are aborted hourly.
// 大文件走 R2 分片。声明的大小与落点由服务端自己记(drive_uploads),不信 complete 请求;
// 过期未完成的由小时级 cron 中止。
