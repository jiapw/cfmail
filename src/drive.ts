/** Turn version keeping on or off. On a file it starts (or stops) remembering what it held; on a
 *  folder it sets the policy that files born beneath it inherit when they are created. A folder
 *  never has versions of its own -- a directory holds no bytes, so there are no earlier copies of
 *  it for anything to keep.
 *  开启或关闭版本保留。对文件,是开始(或停止)记住它装过什么;对文件夹,是设定一条策略,
 *  由其下新生的文件在创建时继承。文件夹自己永远没有版本 ——
 *  目录不装字节,也就不存在"更早的它"可供谁保留。 */
driveApp.post('/nodes/:id/versioning', async (c) => {
  // Owner only. This decides whether the thing can still be deleted outright, and that is not a
  // question the editor of somebody else's shared folder gets to answer on their behalf.
  // 仅限所有者。这决定了这东西还能不能被直接删掉,
  // 而这个问题,轮不到"别人共享目录的编辑者"替他回答。
  const a = await accessNode(c, c.req.param('id'), 'owner');
  if (a.chain.some((n) => n.trashed)) throw new HttpError(400, 'e_drive_trashed');
  const body = await c.req.json<any>();
  const on = !!body.on;
  const t = now();
  if (a.node.kind === 'folder') {
    // A folder's switch speaks for files not yet born and for nothing else. It used to offer to
    // reach down and change the files already there, which made one gesture mean two things --
    // set a rule, and act on everything under it -- and the second was invisible afterwards:
    // nothing on a file says whether its setting came from itself or from a sweep. A file's own
    // history is switched on the file.
    // 一个目录的开关,只为"尚未出生的文件"说话,别的一概不管。它从前会顺手问一句要不要连
    // 已经在那儿的文件一起改,于是同一个动作有了两层含义 —— 定一条规矩,和对其下的一切动手 ——
    // 而后一层事后无从查考:一个文件身上并不写着它的设置是自己的,还是被某次扫过时给的。
    // 一个文件自己的历史,在这个文件上开关。
    await c.env.DB.prepare('UPDATE drive_nodes SET ver_policy=?1, updated_at=?2 WHERE id=?3')
      .bind(on ? 1 : 0, t, a.node.id).run();
    await audit(c.env, c.get('user'), 'drive.versioning', a.node.name, { on, folder: true });
    return c.json({ ok: true, ver_policy: on });
  }
  if (a.node.kind !== 'file') throw new HttpError(400, 'e_drive_not_file');
  if (on && !a.node.versioned) {
    const stmts: D1PreparedStatement[] = [];
    let vid = a.node.ver_head;
    if (!vid && a.node.r2_key) {
      vid = uid();
      stmts.push(versionWrite(c.env, a.node.id, null, {
        id: vid, key: a.node.r2_key, size: a.node.size || 0, mime: a.node.mime || '',
        origin: 'init', author: c.get('user').id, linked: false, at: t,
      }));
    }
    stmts.push(c.env.DB.prepare('UPDATE drive_nodes SET versioned=1, ver_head=?1 WHERE id=?2').bind(vid, a.node.id));
    await c.env.DB.batch(stmts);
    // From here its pointer is allowed to move, so no remembered row may outlive this moment.
    // 从此它的指针可以移动了,于是任何记住的行都不该活过这一刻。
    accessCache.delete(c.get('user').id + ':' + a.node.id);
  } else if (!on && a.node.versioned) {
    // Off puts the file back where it was before anyone asked for history: no past, only what it
    // is now. Keeping the old versions around while collecting no more left the file in a third
    // state that nothing else in the drive has -- a file wearing a version mark that no longer
    // meant anything was being kept -- and every way of saying that in the interface came out
    // sounding like a bug. One switch, two states.
    //
    // The bytes still under the file are exactly the ones the head version names, so the head's
    // object is the one thing here that must survive; every other version owns its own key
    // outright, and those leave with their rows.
    //
    // 关掉,是把文件放回没人要过历史之前的样子:没有过去,只有它现在是什么。
    // 留着旧版本却不再收集新的,会把文件困在一个网盘里别处都没有的第三种状态 ——
    // 一个戴着版本标记、而那个标记已不再意味着任何东西正被保留的文件 ——
    // 而界面上无论怎么描述它,听起来都像一个 bug。一个开关,两种状态。
    //
    // 文件下面那份字节,正是 head 版本所指的那份,所以 head 的对象是这里唯一必须活下来的;
    // 其余每个版本都独占自己的键,它们随各自的行一同离场。
    await dropHistory(c.env, a.node);
  }
  await audit(c.env, c.get('user'), 'drive.versioning', a.node.name, { on });
  return c.json({ ok: true, versioned: on });
});

