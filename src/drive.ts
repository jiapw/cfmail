/** The node and all its ancestors, node first, root last. Empty when the id does not exist.
 *  节点及其全部祖先,节点在前、根在后。id 不存在时为空。 */
async function chainOf(env: Env, nodeId: string): Promise<NodeRow[]> {
  const rows = await env.DB.prepare(
    `WITH RECURSIVE chain AS (
       SELECT n.*, 0 AS depth FROM drive_nodes n WHERE n.id=?1
       UNION ALL
       SELECT p.*, c.depth+1 FROM drive_nodes p JOIN chain c ON p.id=c.parent_id WHERE c.depth<${DEPTH_MAX}
     ) SELECT * FROM chain ORDER BY depth`
  ).bind(nodeId).all();
  return (rows.results || []) as unknown as NodeRow[];
}

interface Access {
  node: NodeRow;
  level: 'owner' | 'editor' | 'viewer';
  /** For share members, the highest shared ancestor -- their movements stay inside this subtree.
   *  共享成员可见范围的顶点 —— 他们的一切操作都被圈在这棵子树里。 */
  shareRoot: string | null;
  chain: NodeRow[];
}

/** Resolve what the current user may do with a node. Owners always pass (even in the trash);
 *  others need a share membership on some ancestor, and anything inside the owner's trash is
 *  invisible to them. Missing and forbidden both answer 404, to not leak existence.
 *  解析当前用户对节点的权限。所有者永远放行(含回收站);其他人需要在某个祖先上有共享成员资格,
 *  且所有者回收站里的内容对他们一律不可见。不存在与无权限统一回 404,不泄露存在性。 */
async function accessNode(c: any, nodeId: string, need: 'view' | 'edit' | 'owner'): Promise<Access> {
  const user: User = c.get('user');
  const chain = await chainOf(c.env, nodeId);
  if (!chain.length) throw new HttpError(404, 'e_drive_not_found');
  const node = chain[0];
  if (node.owner_id === user.id) return { node, level: 'owner', shareRoot: null, chain };
  if (need === 'owner') throw new HttpError(404, 'e_drive_not_found');
  if (chain.some((n) => n.trashed)) throw new HttpError(404, 'e_drive_not_found');
  const ids = chain.map((n) => n.id);
  const rows = await c.env.DB.prepare(
    `SELECT s.node_id, s.role FROM drive_shares s JOIN drive_share_members m ON m.share_id=s.id
     WHERE m.user_id=?1 AND s.node_id IN (${ids.map((_, i) => '?' + (i + 2)).join(',')})`
  ).bind(user.id, ...ids).all();
  const hits = (rows.results || []) as { node_id: string; role: string }[];
  if (!hits.length) throw new HttpError(404, 'e_drive_not_found');
  const level = hits.some((h) => h.role === 'editor') ? 'editor' : 'viewer';
  if (need === 'edit' && level !== 'editor') throw new HttpError(403, 'e_drive_forbidden');
  // Among qualifying shares pick the one closest to the root: the widest subtree
  // 命中多个共享时取离根最近的那个:活动范围最大
  const best = hits
    .filter((h) => level === 'viewer' || h.role === 'editor')
    .sort((a, b) => ids.indexOf(b.node_id) - ids.indexOf(a.node_id))[0];
  return { node, level, shareRoot: best.node_id, chain };
}

function cleanName(v: unknown): string {
  // Control characters and '/' out; everything else (any script) is welcome
  // 去掉控制字符与 '/',其余(任意文字)都放行
  const s = String(v ?? '').replace(/[\u0000-\u001f\u007f/]/g, '').trim();
  if (!s || s.length > NAME_MAX) throw new HttpError(400, 'e_drive_bad_name');
  return s;
}

function cleanMime(v: unknown): string {
  const s = String(v ?? '').toLowerCase().split(';')[0].trim();
  return /^[a-z0-9.+-]+\/[a-z0-9.+-]+$/.test(s) ? s.slice(0, 120) : 'application/octet-stream';
}

function nodeJson(n: any, withShared = true) {
  return {
    id: n.id, parent_id: n.parent_id || null, kind: n.kind, name: n.name, mime: n.mime || '',
    size: n.size || 0, tree_bytes: n.tree_bytes || 0, starred: !!n.starred, trashed: !!n.trashed,
    shared: withShared ? !!n.shared : false, thumb: !!n.has_thumb,
    created_at: n.created_at, updated_at: n.updated_at,
  };
}

/** Ancestor-chain rollup for the materialised folder sizes: one statement, O(depth) rows.
 *  Deltas are plain commutative increments, so any interleaving of concurrent operations
 *  lands on the same totals. Propagation stops at a trashed ancestor: everything above it
 *  already dropped that subtree's contribution when the ancestor was trashed (matters when a
 *  node inside a trashed folder is trashed individually via the API). Returns null when there
 *  is nothing to do.
 *  物化文件夹大小的祖先链上卷。一条语句,O(深度) 行。增量是可交换的加法,并发操作任意交错
 *  结果都一致。传播在已回收祖先处停止:其上层早在该祖先进回收站时就扣掉了整棵子树的贡献
 *  (对"经 API 单独回收已回收文件夹内的节点"这种路径至关重要)。无事可做时返回 null。 */
function ancDelta(env: Env, parentId: string | null | undefined, delta: number): D1PreparedStatement | null {
  if (!parentId || !delta) return null;
  return env.DB.prepare(
    `WITH RECURSIVE anc(id, depth) AS (
       SELECT ?1, 0
       UNION ALL SELECT n.parent_id, a.depth+1 FROM drive_nodes n JOIN anc a ON n.id=a.id
       WHERE n.parent_id IS NOT NULL AND n.trashed=0 AND a.depth<${DEPTH_MAX}
     ) UPDATE drive_nodes SET tree_bytes=MAX(tree_bytes+?2,0) WHERE kind='folder' AND id IN (SELECT id FROM anc)`
  ).bind(parentId, delta);
}

/** The bytes a node contributes to its ancestors: its own size, or its materialised subtree
 *  本节点为祖先贡献的字节数:文件是自身大小,文件夹是其物化子树大小 */
const nodeBytes = (n: NodeRow | any): number => (n.kind === 'file' ? n.size || 0 : n.tree_bytes || 0);

/** Where a create/upload lands: the user's own root, or a folder they can edit (their own or a
 *  shared one -- then the folder owner's drive takes the file). Nothing lands inside a trash.
 *  新建/上传落到哪里:自己的根目录,或一个有编辑权的文件夹(自己的或共享的 —— 后者落入文件夹
 *  所有者的网盘)。回收站里不允许落任何东西。 */
async function resolveWriteTarget(c: any, parent: string): Promise<{ ownerId: string; parentId: string | null }> {
  if (parent === 'root' || !parent) return { ownerId: (c.get('user') as User).id, parentId: null };
  const a = await accessNode(c, parent, 'edit');
  if (a.node.kind !== 'folder') throw new HttpError(400, 'e_drive_not_folder');
  if (a.chain.some((n) => n.trashed)) throw new HttpError(400, 'e_drive_trashed');
  if (a.chain.length >= DEPTH_MAX - 1) throw new HttpError(400, 'e_drive_too_deep');
  return { ownerId: a.node.owner_id, parentId: a.node.id };
}

/** The Drive forbids duplicate names per folder and kind. This finds the standing occupant of a
 *  name so uploads can overwrite it and renames can refuse it. Ranked newest-first because
 *  legacy data may still hold duplicates from before the rule.
 *  网盘按目录和类型禁止重名。此函数找出当前占着某个名字的节点。上传用它来覆盖,
 *  改名用它来拒绝。按最新排序,因为规则之前的存量数据可能已有重名。 */
async function findClash(env: Env, ownerId: string, parentId: string | null, name: string, kind: string): Promise<NodeRow | null> {
  const sql = parentId
    ? 'SELECT * FROM drive_nodes WHERE owner_id=?1 AND parent_id=?2 AND name=?3 AND kind=?4 AND trashed=0 ORDER BY updated_at DESC LIMIT 1'
    : 'SELECT * FROM drive_nodes WHERE owner_id=?1 AND parent_id IS NULL AND name=?2 AND kind=?3 AND trashed=0 ORDER BY updated_at DESC LIMIT 1';
  const binds = parentId ? [ownerId, parentId, name, kind] : [ownerId, name, kind];
  const row = await env.DB.prepare(sql).bind(...binds).first();
  return (row as unknown as NodeRow) || null;
}

/** Drop rows whose ancestors include a trashed folder (used by search/starred/recent, where the
 *  query alone cannot see implicit trash membership). Chain lookups are memoised per parent.
 *  过滤掉祖先在回收站里的行(搜索/星标/最近用 —— 单条查询看不出"隐式在回收站")。按父节点缓存。 */
async function dropTrashedAncestors(env: Env, rows: any[]): Promise<any[]> {
  const bad = new Map<string, boolean>();
  const out: any[] = [];
  for (const r of rows) {
    if (r.trashed) continue;
    if (!r.parent_id) { out.push(r); continue; }
    if (!bad.has(r.parent_id)) {
      const chain = await chainOf(env, r.parent_id);
      let b = !chain.length;
      for (let i = chain.length - 1; i >= 0; i--) {
        b = b || !!chain[i].trashed;
        bad.set(chain[i].id, b);
      }
      if (!chain.length) bad.set(r.parent_id, true);
    }
    if (!bad.get(r.parent_id)) out.push(r);
  }
  return out;
}

/** Permanently delete up to `limit` nodes of the subtree at rootId, deepest first (children always
 *  go before their parent, so an interrupted run leaves a consistent tree). Removes R2 objects,
 *  share rows and refunds the owner's quota. Returns how many nodes remain.
 *  彻底删除以 rootId 为根的子树,一次最多 limit 个节点、最深的先删(孩子永远先于父亲,中断后树仍
 *  一致)。连带删 R2 对象与共享记录,并退还所有者配额。返回还剩多少节点。 */
export async function purgeSubtree(env: Env, rootId: string, limit = PURGE_BATCH): Promise<number> {
  const rows = await env.DB.prepare(
    `WITH RECURSIVE sub(id, depth) AS (
       SELECT id, 0 FROM drive_nodes WHERE id=?1
       UNION ALL SELECT n.id, s.depth+1 FROM drive_nodes n JOIN sub s ON n.parent_id=s.id WHERE s.depth<${DEPTH_MAX}
     ) SELECT n.id, n.kind, n.size, n.r2_key, n.owner_id FROM sub JOIN drive_nodes n ON n.id=sub.id
     ORDER BY sub.depth DESC`
  ).bind(rootId).all();
  const all = (rows.results || []) as any[];
  if (!all.length) return 0;
  const batch = all.slice(0, limit);
  // Each file may carry a thumbnail at <r2_key>.t -- delete it in the same sweep.
  // R2 bulk delete silently skips keys that do not exist.
  // 每个文件旁可能有 <r2_key>.t 的缩略图,同一批顺手删掉。R2 批量删除对不存在的键静默跳过。
  const keys = batch.flatMap((n) => (n.r2_key ? [n.r2_key, n.r2_key + THUMB_SUFFIX] : []));
  for (let i = 0; i < keys.length; i += 900) {
    await env.RAW.delete(keys.slice(i, i + 900)).catch(() => {});
  }
  const freed = batch.reduce((s, n) => s + (n.kind === 'file' ? n.size || 0 : 0), 0);
  const stmts: D1PreparedStatement[] = [];
  for (let i = 0; i < batch.length; i += 90) {
    const part = batch.slice(i, i + 90).map((n) => n.id);
    const ph = part.map((_, j) => '?' + (j + 1)).join(',');
    // Members must go before their shares (the subquery still needs the share rows)
    // 成员先于共享删(子查询还要用到共享行)
    stmts.push(env.DB.prepare(
      `DELETE FROM drive_share_members WHERE share_id IN (SELECT id FROM drive_shares WHERE node_id IN (${ph}))`
    ).bind(...part));
    stmts.push(env.DB.prepare(`DELETE FROM drive_shares WHERE node_id IN (${ph})`).bind(...part));
    stmts.push(env.DB.prepare(`DELETE FROM drive_nodes WHERE id IN (${ph})`).bind(...part));
  }
  if (freed > 0) {
    stmts.push(env.DB.prepare('UPDATE users SET drive_bytes=MAX(drive_bytes-?1,0) WHERE id=?2').bind(freed, batch[0].owner_id));
  }
  await env.DB.batch(stmts);
  return all.length - batch.length;
}

