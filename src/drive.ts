/** Effective quota and usage. enabled=false when none of the user's domains has Drive switched on.
 *  生效配额与用量。用户所属域名都没开网盘时 enabled=false。 */
export async function driveQuota(env: Env, userId: string): Promise<Quota> {
  const row = await env.DB.prepare(
    `SELECT u.drive_quota_mb AS user_mb, u.drive_bytes AS used,
       (SELECT MAX(d.drive_quota_mb) FROM domains d WHERE d.drive_enabled=1 AND d.id IN
         (SELECT mb.domain_id FROM grants g JOIN mailboxes mb ON mb.id=g.mailbox_id WHERE g.user_id=u.id)) AS dom_mb
     FROM users u WHERE u.id=?1`
  ).bind(userId).first<any>();
  const enabled = !!row && row.dom_mb != null;
  const mb = Math.min(row?.user_mb ?? row?.dom_mb ?? 0, DRIVE_HARD_CAP_MB);
  return { enabled, quota: mb * MB, used: row?.used || 0 };
}

/** Room for `add` more bytes in the owner's drive -- the owner's, not the uploader's: files created
 *  in a shared folder are charged to the folder owner.
 *  校验所有者还装得下 add 字节 —— 是所有者、不是操作者:传进共享文件夹的文件记在文件夹所有者的配额上。 */
async function checkQuota(env: Env, ownerId: string, add: number): Promise<void> {
  const q = await driveQuota(env, ownerId);
  if (!q.enabled) throw new HttpError(403, 'e_drive_disabled');
  if (q.used + add > q.quota) throw new HttpError(413, 'e_drive_quota');
}

