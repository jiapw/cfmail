// zh-TW interface strings.
//
// One file per language, fetched only when that language is the one in use. They were a single
// object in i18n.js until it reached half a megabyte, all nine of which every reader downloaded
// to use one -- on a phone that is the largest thing on the page by a wide margin.
//
// Add a string by adding it to every one of the nine. i18n.js falls back to the key itself, so a
// language that is missing an entry shows the key rather than another language's words, which is
// how a gap makes itself known instead of hiding.
//
// zh-TW 界面词条。
//
// 每种语言一个文件,只在它正被使用时才取。它们本来是 i18n.js 里的一个对象,直到那个文件长到
// 半兆 —— 而每个读者为了用其中一种,把九种全下载下来;在手机上,那是整页里最大的一样东西。
//
// 加词条要九个文件一起加。i18n.js 找不到就回退到键名本身,所以缺词条的语言显示的是键名,
// 而不是另一种语言的句子 —— 一个缺口就是这样让自己被看见的,而不是藏起来。

